    #[test]
    fn range_update_codec_is_bounded_and_canonical() {
        let opening: Vec<_> = (0..9)
            .map(|position| update_test_digest(b"opening", position))
            .collect();
        let tree = update_test_tree(&opening);
        let closing = update_test_digest(b"closing", 4);
        let update = tree.update::<Sha256>(&[(4, closing)], &Sequential).unwrap();
        let proof = tree
            .range_update_proofs(&update, &[0, 3, 7, 9], &Sequential)
            .unwrap()
            .remove(1);
        let encoded = proof.encode();
        assert_eq!(encoded.len(), proof.encode_size());
        assert_eq!(
            RangeUpdateProof::<Digest>::decode_cfg(
                encoded.clone(),
                &(proof.shared.len(), proof.outside.len()),
            )
            .unwrap(),
            proof
        );
        if !proof.shared.is_empty() {
            assert!(
                RangeUpdateProof::<Digest>::decode_cfg(
                    encoded.clone(),
                    &(proof.shared.len() - 1, proof.outside.len()),
                )
                .is_err()
            );
        }
        if !proof.outside.is_empty() {
            assert!(
                RangeUpdateProof::<Digest>::decode_cfg(
                    encoded.clone(),
                    &(proof.shared.len(), proof.outside.len() - 1),
                )
                .is_err()
            );
        }

        let mut truncated = encoded;
        truncated.truncate(truncated.len() - 1);
        assert!(
            RangeUpdateProof::<Digest>::decode_cfg(
                truncated,
                &(proof.shared.len(), proof.outside.len()),
            )
            .is_err()
        );
    }

    #[cfg(feature = "arbitrary")]
    mod conformance {
        use super::*;
        use commonware_codec::conformance::CodecConformance;
        use commonware_conformance::Conformance;
        use commonware_cryptography::sha256::Digest as Sha256Digest;

        fn test_merkle_tree(n: usize) -> Digest {
            // Build tree
            let mut digests = Vec::with_capacity(n);
            let mut builder = Builder::<Sha256>::new(n);
            for i in 0..n {
                let digest = Sha256::hash(&[&i.to_be_bytes()]);
                builder.add(&digest);
                digests.push(digest);
            }
            let tree = builder.build(&Sequential);
            let root = tree.root();

            // For each leaf, generate and verify its proof
            for (i, leaf) in digests.iter().enumerate() {
                // Generate proof
                let proof = tree.proof(i as u32).unwrap();
                assert!(
                    proof
                        .verify_element_inclusion::<Sha256>(leaf, i as u32, &root)
                        .is_ok(),
                    "correct fail for size={n} leaf={i}"
                );

                // Serialize and deserialize the proof
                let serialized = proof.encode();
                let deserialized = Proof::<Digest>::decode_cfg(serialized, &1).unwrap();
                assert!(
                    deserialized
                        .verify_element_inclusion::<Sha256>(leaf, i as u32, &root)
                        .is_ok(),
                    "deserialize fail for size={n} leaf={i}"
                );

                // Modify a sibling hash and ensure the proof fails
                if !proof.siblings.is_empty() {
                    let mut update_tamper = proof.clone();
                    update_tamper.siblings[0] = Sha256::hash(&[b"tampered"]);
                    assert!(
                        update_tamper
                            .verify_element_inclusion::<Sha256>(leaf, i as u32, &root)
                            .is_err(),
                        "modify fail for size={n} leaf={i}"
                    );
                }

                // Add a sibling hash and ensure the proof fails
                let mut add_tamper = proof.clone();
                add_tamper.siblings.push(Sha256::hash(&[b"tampered"]));
                assert!(
                    add_tamper
                        .verify_element_inclusion::<Sha256>(leaf, i as u32, &root)
                        .is_err(),
                    "add fail for size={n} leaf={i}"
                );

                // Remove a sibling hash and ensure the proof fails
                if !proof.siblings.is_empty() {
                    let mut remove_tamper = proof.clone();
                    remove_tamper.siblings.pop();
                    assert!(
                        remove_tamper
                            .verify_element_inclusion::<Sha256>(leaf, i as u32, &root)
                            .is_err(),
                        "remove fail for size={n} leaf={i}"
                    );
                }
            }

            // Test proof for larger than size
            assert!(tree.proof(n as u32).is_err());

            // Return the root so we can ensure we don't silently change.
            root
        }

        struct RootConformance;

        impl Conformance for RootConformance {
            async fn commit(seed: u64) -> Vec<u8> {
                let root = test_merkle_tree(seed as usize);
                root.to_vec()
            }
        }

        commonware_conformance::conformance_tests! {
            CodecConformance<Proof<Sha256Digest>>,
            CodecConformance<RangeUpdateProof<Sha256Digest>>,
            RootConformance => 200
        }
    }
