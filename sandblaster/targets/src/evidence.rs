    /// A campaign document: every x86 model passing with 10^7 cases, except
    /// the SHA-NI models skipped (with FIPS consistency) when `sha` is false
    /// and model `fail` (if any) failing; core records attached.
    fn campaign(m: &Machine, sha: bool, fail: Option<usize>) -> Json {
        let arch = Arch::X86_64;
        let cfg = Config { random_per_model: REQUIRED_RANDOM_CASES, seed: 1 };
        let hw: Vec<Outcome> = arch
            .models()
            .iter()
            .enumerate()
            .map(|(i, md)| {
                if !sha && md.features.contains(&"sha") {
                    return Outcome::skipped(md.name, "CPU lacks sha");
                }
                let mut o = crate::diff::diff1(md.name, 1, 1, |x: u32| x, |x: u32| if Some(i) == fail { x ^ 1 } else { x });
                o.random = REQUIRED_RANDOM_CASES;
                o
            })
            .collect();
        let cons: Vec<Outcome> = arch
            .models()
            .iter()
            .filter(|md| md.features.contains(&"sha"))
            .map(|md| crate::diff::diff1(md.name, 1, 1, |x: u32| x, |x: u32| x))
            .collect();
        let mut doc = render(arch, m, &cfg, &hw, &cons, &[]);
        attach_core(&mut doc, m);
        doc
    }

