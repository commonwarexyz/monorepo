// Host runs of the feature-only variant sets

/// One host run of a feature-only variant set's clones (design §13.2,
/// §19.2): the set's generated clones (called directly, or through the
/// dispatcher with the detection forced) ran a differential or fixture
/// suite on one CPU, and agreed with the portable code on `cases` inputs
/// or not. A feature-only set's clones use Rust primitives compiled under
/// `#[target_feature]` (no intrinsic model), so this is the hardware half
/// of their evidence: that the CPU executes the set's instructions as the
/// primitives mean them (a `lzcnt` that runs as `bsr` gives wrong answers,
/// not faults).
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct SetRecord {
    /// The CPU key ([`Machine::cpu_key`]).
    pub cpu_key: String,
    /// `native`, `rosetta2`, ... ([`VALIDATING_EXECUTORS`]).
    pub executor: String,
    /// The set's name (`v3_scalar`, `v4`, `sha_sse2_ssse3_sse4_1_v3`).
    pub set: String,
    /// [`set_hash`] of the set as it ran.
    pub set_hash: String,
    /// The suite (`qmdb-fixtures-n1`, `qmdb-fixtures-n32`,
    /// `shape-differential`, ...).
    pub suite: String,
    /// Inputs compared with the portable code.
    pub cases: u64,
    /// Inputs on which the set's clones disagreed.
    pub mismatches: u64,
    /// `passed`, `failed`, `skipped` or `diagnostic` ([`set_run_status`]).
    pub status: String,
    /// The set's features the CPU does not report (the run forced the set
    /// onto it: a diagnostic, never evidence).
    pub unreported: Vec<String>,
}

impl SetRecord {
    /// This one run passed on its CPU: the status recomputed from the counts
    /// ([`set_run_status`]) is `passed` and agrees with the recorded one
    /// (something ran, no mismatch, every feature reported by the CPU), on
    /// an executor that may validate. One such run is not enough for the
    /// set: [`set_verdict_in`] needs every suite of [`SET_SUITES`] on the
    /// same CPU, each with at least [`set_suite_min_cases`] cases.
    pub fn counts_as_evidence(&self) -> bool {
        self.status == "passed" && set_run_status(self.cases, self.mismatches, &self.unreported) == "passed" && executor_may_validate(&self.executor)
    }

    /// Why this run withdraws its set everywhere, if it does: any mismatch
    /// (whatever the status says, as [`merge_files`] counts failures), a
    /// `failed` status, or a status that disagrees with the counts
    /// ([`set_run_status`]; the record was edited or corrupted).
    pub fn failure(&self) -> Option<String> {
        let recomputed = set_run_status(self.cases, self.mismatches, &self.unreported);
        if self.mismatches > 0 || self.status == "failed" {
            Some(format!("the set's clones disagreed with the portable code on {} ({}: {} of {} inputs, status `{}`)", self.cpu_key, self.suite, self.mismatches, self.cases, self.status))
        } else if self.status != recomputed {
            Some(format!("the run of {} on {} records status `{}` but its counts give `{recomputed}` ({} cases, {} mismatches, unreported [{}])", self.suite, self.cpu_key, self.status, self.cases, self.mismatches, self.unreported.join(", ")))
        } else {
            None
        }
    }
}

/// The suites a CPU must pass, all of them, before a feature-only set counts
/// as validated there: the ones the host-kit harness
/// (`sandblaster/front/tests/host_sets.rs`) runs for every set.
pub const SET_SUITES: [&str; 4] = ["qmdb-fixtures-n1", "qmdb-fixtures-n32", "shape-differential-n1", "shape-differential-n32"];

/// The prefix of a **lane kernel**'s set name (plan O10:
/// `lanes:<target>:<emission hash>`). The hash covers the Rust code the
/// host compiles and runs: the kernel item as printed (tokens, doc comments
/// and visibility left out), the text of every load/store helper and
/// checked-arithmetic helper it calls, and the compiler
/// ([`BUILD_RUSTC`]); see `sandblaster_front::opt::par::lane_fingerprint`.
/// A change to the printer, a helper template or the toolchain therefore
/// renames the set, and the old runs stop counting. A lane kernel uses
/// validated intrinsic models only, but their composition runs on real
/// hardware only after a host has run it differentially against the
/// portable lane site: it is gated like a feature-only set, with its own
/// suite ([`LANE_SUITES`]).
pub const LANE_SET_PREFIX: &str = "lanes:";

/// `rustc -V` of the compiler that built this crate. The lane kernels'
/// set names include it ([`LANE_SET_PREFIX`]): a host run counts only for
/// builds by the same compiler.
pub const BUILD_RUSTC: &str = env!("SANDBLASTER_TARGETS_RUSTC_VERSION");

/// The suite a CPU must pass before a lane kernel counts as validated
/// there: the host kit's `lanes` stage (the kernel against its site on
/// random inputs, [`REQUIRED_LANE_CASES`] of them).
pub const LANE_SUITES: [&str; 1] = ["lane-differential"];

/// The fewest inputs a lane differential needs to count.
pub const REQUIRED_LANE_CASES: u64 = 1_000_000;

/// The suites of the set `name` ([`SET_SUITES`], or [`LANE_SUITES`] for a
/// lane kernel).
pub fn set_suites(name: &str) -> &'static [&'static str] {
    if name.starts_with(LANE_SET_PREFIX) { &LANE_SUITES } else { &SET_SUITES }
}

/// The fewest random `shape` inputs a shape differential needs to count
/// (the harness default; a host-kit dry run uses 2·10^4 and so never
/// counts).
pub const REQUIRED_SHAPE_CASES: u64 = 1_000_000;

/// The fewest cases a run of `suite` needs to count as evidence:
/// [`REQUIRED_SHAPE_CASES`] for a shape differential, one for a fixture
/// suite (which always runs the whole fixture corpus).
pub fn set_suite_min_cases(suite: &str) -> u64 {
    if suite.starts_with("shape-differential") {
        REQUIRED_SHAPE_CASES
    } else if suite == "lane-differential" {
        REQUIRED_LANE_CASES
    } else {
        1
    }
}

/// The statuses a set run may record ([`set_run_status`]).
const SET_STATUSES: [&str; 4] = ["passed", "failed", "skipped", "diagnostic"];

/// The hash that ties set runs to the set as the optimizer defines it:
/// its name and its feature closure (sorted). A set whose features change
/// has no evidence until it runs again.
pub fn set_hash(name: &str, features: &[String]) -> String {
    let mut fs: Vec<&str> = features.iter().map(String::as_str).collect();
    fs.sort_unstable();
    fs.dedup();
    let text = format!("sandblaster-feature-set/1\n{name}\n{}\n", fs.join(","));
    format!("sha256:{}", fips::hex(&fips::sha256(text.as_bytes())))
}

/// The status of one set run: `diagnostic` when the CPU does not report
/// every feature of the set (the run forced it), else `skipped` when
/// nothing ran, `failed` on any mismatch, `passed` otherwise.
pub fn set_run_status(cases: u64, mismatches: u64, unreported: &[String]) -> &'static str {
    if !unreported.is_empty() {
        "diagnostic"
    } else if cases == 0 {
        "skipped"
    } else if mismatches > 0 {
        "failed"
    } else {
        "passed"
    }
}

/// The JSON record of one set run on `machine` ([`SetRecord`]; `source`
/// says how the counts were obtained).
#[allow(clippy::too_many_arguments)]
pub fn set_run_json(machine: &Machine, set: &str, features: &[String], suite: &str, cases: u64, mismatches: u64, source: &str) -> Json {
    let mut fs: Vec<String> = features.to_vec();
    fs.sort();
    fs.dedup();
    let unreported: Vec<String> = fs.iter().filter(|f| !machine.detected_features.iter().any(|(n, on)| n == *f && *on)).cloned().collect();
    Json::Obj(vec![
        ("cpu_key".into(), Json::str(machine.cpu_key())),
        ("executor".into(), Json::str(machine.executor.clone())),
        ("cpu_brand_string".into(), Json::str(machine.cpu_brand_string.clone())),
        ("rustc".into(), Json::str(machine.rustc.clone())),
        ("set".into(), Json::str(set)),
        ("features".into(), Json::Arr(fs.iter().map(|f| Json::str(f.clone())).collect())),
        ("set_hash".into(), Json::str(set_hash(set, &fs))),
        ("suite".into(), Json::str(suite)),
        ("cases".into(), Json::uint(cases)),
        ("mismatches".into(), Json::uint(mismatches)),
        ("status".into(), Json::str(set_run_status(cases, mismatches, &unreported))),
        ("unreported_features".into(), Json::Arr(unreported.iter().map(|f| Json::str(f.clone())).collect())),
        ("target".into(), Json::str(machine.target.clone())),
        ("date".into(), Json::str(machine.date.clone())),
        ("source".into(), Json::str(source)),
    ])
}

/// Records a set run in `doc` (a schema-3 record): the entry of the same
/// CPU, set and suite is replaced, every other kept. (The run describes its
/// machine itself; the top-level `hosts` list the model campaigns' machines.)
pub fn with_set_run(doc: &mut Json, entry: Json) {
    let id = |j: &Json| (host_key(j).map(str::to_string), j.get("set").and_then(Json::as_str).map(str::to_string), j.get("suite").and_then(Json::as_str).map(str::to_string));
    let key = id(&entry);
    let mut sets: Vec<Json> = doc.get("sets").and_then(Json::as_array).unwrap_or(&[]).iter().filter(|e| id(e) != key).cloned().collect();
    sets.push(entry);
    set_member(doc, "sets", Json::Arr(sets));
}

/// The verdict on a feature-only variant set.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum SetVerdict {
    /// Some CPU ran the set's clones against the portable code in every
    /// suite of [`SET_SUITES`], passed each, and reports every feature of
    /// the set; no current run failed anywhere.
    Validated {
        /// The CPU keys with such a run, sorted.
        cpus: Vec<String>,
    },
    /// No usable evidence, with the reason.
    Missing(String),
}

/// The fail-closed verdict on the set `name` with the feature closure
/// `features` in `file`. Only runs of the set as defined now count
/// ([`set_hash`]). Any current failure ([`SetRecord::failure`]: a mismatch,
/// a `failed` status, or a status the counts contradict) → missing. Else
/// validated on every CPU that has a run counting as evidence
/// ([`SetRecord::counts_as_evidence`]) for each suite of [`SET_SUITES`],
/// each with at least [`set_suite_min_cases`] cases, and that no other
/// record of the file says lacks one of the features (a set run listing it
/// as unreported, or the CPU's host summary). Else missing, with what was
/// recorded (incomplete runs, diagnostic ones, or nothing).
pub fn set_verdict_in(file: &EvidenceFile, name: &str, features: &[String]) -> SetVerdict {
    let hash = set_hash(name, features);
    let cur: Vec<&SetRecord> = file.sets.iter().filter(|r| r.set == name && r.set_hash == hash).collect();
    if let Some(why) = cur.iter().find_map(|r| r.failure()) {
        return SetVerdict::Missing(why);
    }
    // A CPU counts when it has a passing run of every suite, each large
    // enough, and nothing else in the file says it lacks one of the set's
    // features.
    let mut keys: Vec<&str> = cur.iter().filter(|r| r.counts_as_evidence()).map(|r| r.cpu_key.as_str()).collect();
    keys.sort_unstable();
    keys.dedup();
    let mut cpus = Vec::new();
    let mut partial = Vec::new();
    for key in keys {
        if let Some(why) = cpu_lacks_features(file, key, features) {
            partial.push(format!("{key}: {why}"));
            continue;
        }
        let missing: Vec<&str> = set_suites(name)
            .iter()
            .copied()
            .filter(|s| !cur.iter().any(|r| r.cpu_key == key && r.suite == *s && r.counts_as_evidence() && r.cases >= set_suite_min_cases(s)))
            .collect();
        if missing.is_empty() {
            cpus.push(key.to_string());
        } else {
            partial.push(format!("{key}: no passing run of {} (a shape differential needs at least {REQUIRED_SHAPE_CASES} cases)", missing.join(", ")));
        }
    }
    if !cpus.is_empty() {
        return SetVerdict::Validated { cpus };
    }
    if !partial.is_empty() {
        return SetVerdict::Missing(format!("incomplete runs: {}", partial.join("; ")));
    }
    let diag: Vec<String> = cur.iter().filter(|r| r.status == "diagnostic").map(|r| format!("{} on {} (the CPU does not report {})", r.suite, r.cpu_key, r.unreported.join(", "))).collect();
    if !diag.is_empty() {
        return SetVerdict::Missing(format!("only diagnostic runs: {}", diag.join("; ")));
    }
    if let Some(r) = cur.iter().find(|r| r.status == "passed" && !executor_may_validate(&r.executor)) {
        return SetVerdict::Missing(format!("run only under the executor `{}` ({}), which never enables dispatch", r.executor, r.cpu_key));
    }
    if name.starts_with(LANE_SET_PREFIX) {
        return SetVerdict::Missing("no host has run the lane kernel (tools/host-kit, stage `lanes`)".to_string());
    }
    SetVerdict::Missing("no host has run the set's clones (tools/host-kit, stage `sets`)".to_string())
}

/// Whether the evidence file says the CPU `key` does not report one of
/// `features`: some set run on that CPU (of any set, as defined at any
/// time) lists it as unreported, or the CPU's host summary records it as
/// not detected. A run that claims otherwise is not evidence.
fn cpu_lacks_features(file: &EvidenceFile, key: &str, features: &[String]) -> Option<String> {
    let mut lacking: Vec<&str> = Vec::new();
    for r in file.sets.iter().filter(|r| r.cpu_key == key) {
        lacking.extend(r.unreported.iter().map(String::as_str).filter(|f| features.iter().any(|g| g == f)));
    }
    for h in file.hosts.iter().filter(|h| h.cpu_key == key) {
        lacking.extend(h.detected_features.iter().filter(|(f, on)| !*on && features.iter().any(|g| g == f)).map(|(f, _)| f.as_str()));
    }
    lacking.sort_unstable();
    lacking.dedup();
    (!lacking.is_empty()).then(|| format!("other records of this CPU say it does not report {}", lacking.join(", ")))
}

/// [`set_verdict_in`] on the committed record of `arch`.
pub fn set_validation(arch: Arch, name: &str, features: &[String]) -> SetVerdict {
    match load(arch) {
        Ok(file) => set_verdict_in(&file, name, features),
        Err(e) => SetVerdict::Missing(e),
    }
}

