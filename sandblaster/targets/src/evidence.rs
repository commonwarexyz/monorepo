// Source hashing

/// The text of item `name` (`pub fn name` or `pub type name`) in `source`,
/// from `pub` to the end of the item, or `None` if it is not found.
///
/// Brace matching skips string literals, character literals and `//`
/// comments, so braces inside `assert!` messages do not confuse it.
pub fn item_text<'a>(source: &'a str, name: &str) -> Option<&'a str> {
    let bytes = source.as_bytes();
    for (kind, terminator) in [("pub fn ", b'{'), ("pub type ", b';')] {
        let needle = format!("{kind}{name}");
        let mut from = 0;
        while let Some(pos) = source[from..].find(&needle) {
            let start = from + pos;
            from = start + needle.len();
            // Must be a whole identifier at the start of a line.
            let next = bytes.get(start + needle.len()).copied().unwrap_or(b' ');
            if next.is_ascii_alphanumeric() || next == b'_' {
                continue;
            }
            let line_start = source[..start].rfind('\n').map_or(0, |i| i + 1);
            if !source[line_start..start].chars().all(char::is_whitespace) {
                continue;
            }
            return if terminator == b';' {
                statement_end(bytes, start).map(|e| &source[start..e])
            } else {
                block_end(bytes, start).map(|e| &source[start..e])
            };
        }
    }
    None
}

/// End (exclusive) of the `;`-terminated item at `start`, skipping `;` nested
/// in brackets or parentheses (`pub type T = [u8; 16];`).
fn statement_end(s: &[u8], start: usize) -> Option<usize> {
    let mut depth = 0usize;
    for (i, &c) in s.iter().enumerate().skip(start) {
        match c {
            b'[' | b'(' => depth += 1,
            b']' | b')' => depth = depth.checked_sub(1)?,
            b';' if depth == 0 => return Some(i + 1),
            _ => {}
        }
    }
    None
}

/// End (exclusive) of the first brace-delimited block at or after `start`.
fn block_end(s: &[u8], start: usize) -> Option<usize> {
    let mut i = start;
    let mut depth = 0usize;
    while i < s.len() {
        match s[i] {
            b'"' => {
                i += 1;
                while i < s.len() && s[i] != b'"' {
                    if s[i] == b'\\' {
                        i += 1;
                    }
                    i += 1;
                }
            }
            b'\'' => {
                // A character literal ('x', '\n', '\''), or a lifetime.
                if s.get(i + 1) == Some(&b'\\') {
                    i += 2;
                    while i < s.len() && s[i] != b'\'' {
                        i += 1;
                    }
                } else if s.get(i + 2) == Some(&b'\'') {
                    i += 2;
                }
            }
            b'/' if s.get(i + 1) == Some(&b'/') => {
                while i < s.len() && s[i] != b'\n' {
                    i += 1;
                }
                continue;
            }
            b'{' => depth += 1,
            b'}' => {
                depth = depth.checked_sub(1)?;
                if depth == 0 {
                    return Some(i + 1);
                }
            }
            _ => {}
        }
        i += 1;
    }
    None
}

/// Multi-character operators, longest first (Rust's maximal-munch lexing).
const OPERATORS: [&str; 24] = [
    "<<=", ">>=", "...", "..=", "::", "->", "=>", "==", "!=", "<=", ">=", "&&", "||", "+=", "-=",
    "*=", "/=", "%=", "^=", "&=", "|=", "<<", ">>", "..",
];

/// Lex item text into Rust tokens: identifiers/keywords/numbers, string and
/// character literals (verbatim), lifetimes, and punctuation with
/// maximal-munch multi-character operators. Whitespace and comments are
/// dropped, so formatting (`rustfmt`) and comments do not change a model's
/// hash, while two token streams are equal only if the code is.
pub fn tokens(text: &str) -> Vec<&str> {
    let s = text.as_bytes();
    let mut out = Vec::new();
    let mut i = 0;
    while i < s.len() {
        let c = s[i];
        let start = i;
        if c.is_ascii_whitespace() {
            i += 1;
            continue;
        }
        if s[i..].starts_with(b"//") {
            while i < s.len() && s[i] != b'\n' {
                i += 1;
            }
            continue;
        }
        if s[i..].starts_with(b"/*") {
            let mut depth = 0usize;
            while i < s.len() {
                if s[i..].starts_with(b"/*") {
                    depth += 1;
                    i += 2;
                } else if s[i..].starts_with(b"*/") {
                    depth -= 1;
                    i += 2;
                    if depth == 0 {
                        break;
                    }
                } else {
                    i += 1;
                }
            }
            continue;
        }
        if c == b'"' {
            i += 1;
            while i < s.len() && s[i] != b'"' {
                i += if s[i] == b'\\' { 2 } else { 1 };
            }
            i = (i + 1).min(s.len());
        } else if c == b'\'' {
            // Character literal ('x', '\n', '\u{..}') or lifetime ('a).
            if s.get(i + 1) == Some(&b'\\') {
                i += 2;
                while i < s.len() && s[i] != b'\'' {
                    i += 1;
                }
                i = (i + 1).min(s.len());
            } else if s.get(i + 2) == Some(&b'\'') {
                i += 3;
            } else {
                i += 1;
                while i < s.len() && (s[i].is_ascii_alphanumeric() || s[i] == b'_') {
                    i += 1;
                }
            }
        } else if c.is_ascii_alphanumeric() || c == b'_' || c >= 0x80 {
            while i < s.len() && (s[i].is_ascii_alphanumeric() || s[i] == b'_' || s[i] >= 0x80) {
                i += 1;
            }
        } else if let Some(op) = OPERATORS
            .iter()
            .find(|op| s[i..].starts_with(op.as_bytes()))
        {
            i += op.len();
        } else {
            i += 1;
        }
        out.push(&text[start..i]);
    }
    out
}

/// Normalize item text for hashing: its token stream joined by single spaces.
fn normalize(text: &str) -> String {
    tokens(text).join(" ")
}

/// The normalized text of one registry item; panics if the item is missing
/// (the registry test guarantees it is not).
pub fn registry_item_text(item: &Item) -> String {
    let text = item_text(item.source.text(), item.name).unwrap_or_else(|| {
        panic!(
            "model item `{}` not found in {}",
            item.name,
            item.source.path()
        )
    });
    normalize(text)
}

/// `sha256:<hex>` of a model's source items: the concatenation over its items
/// of `"<name>\n<token stream joined by spaces>\n"`.
pub fn model_hash(model: &Model) -> String {
    // Memoized, because the optimizer asks for every intrinsic of every
    // printed function. The hash is a function of `model.items` alone (item
    // names and the compiled-in source text), so the memo is keyed by the
    // items' content, never by the `Model`'s address: a temporary `Model`
    // (the type is `Clone` with public fields) can reuse the address of
    // another one and must still get its own hash.
    static MEMO: std::sync::Mutex<Vec<(&'static [Item], String)>> = std::sync::Mutex::new(Vec::new());
    if let Some((_, h)) = MEMO.lock().unwrap_or_else(|e| e.into_inner()).iter().find(|(k, _)| *k == model.items) {
        return h.clone();
    }
    let h = model_hash_uncached(model);
    MEMO.lock().unwrap_or_else(|e| e.into_inner()).push((model.items, h.clone()));
    h
}

fn model_hash_uncached(model: &Model) -> String {
    let mut input = String::new();
    for item in model.items {
        input.push_str(item.name);
        input.push('\n');
        input.push_str(&registry_item_text(item));
        input.push('\n');
    }
    format!("sha256:{}", fips::hex(&fips::sha256(input.as_bytes())))
}

