/// One model's record as read back from an evidence file.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Record {
    /// Model name.
    pub name: String,
    /// Recorded source hash.
    pub source_hash: String,
    /// Recorded status.
    pub status: Status,
    /// Random cases against hardware (0 if skipped).
    pub random_cases: u64,
    /// Corner cases against hardware.
    pub corner_cases: u64,
    /// Mismatches against hardware.
    pub mismatches: u64,
    /// The core-text record, if present.
    pub core: Option<CoreRecord>,
    /// Per-CPU entries (schema 3; empty for older files).
    pub hosts: Vec<HostEntry>,
}

/// One model's result on one CPU (schema 3 `hosts` entry).
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct HostEntry {
    /// The CPU key ([`cpu::CpuId::key_on`] or a `legacy:` key).
    pub cpu_key: String,
    /// `native`, `rosetta2`, ...
    pub executor: String,
    /// The model hash the campaign compared against.
    pub source_hash: String,
    /// Status on that CPU.
    pub status: Status,
    /// Random cases against the hardware.
    pub random_cases: u64,
    /// Corner cases against the hardware.
    pub corner_cases: u64,
    /// Mismatches.
    pub mismatches: u64,
}

impl HostEntry {
    /// Validated with enough random cases and no mismatch, on an executor
    /// that may enable dispatch ([`executor_may_validate`]).
    pub fn counts_as_validated(&self) -> bool {
        self.status == Status::Validated && self.mismatches == 0 && self.random_cases >= REQUIRED_RANDOM_CASES && executor_may_validate(&self.executor)
    }
}

/// The executors whose results may validate a model: native hardware, and
/// Rosetta 2 (the record the repository started from). An allowlist, so
/// that anything else — an instruction emulator the probe detected (`sde`,
/// `qemu-tcg`, `valgrind`, ...), one the kit named explicitly (`emulated`,
/// `--executor`), a misspelling, or a missing field (parsed as `unknown`) —
/// is recorded but never validates (design §13.5: "Intel SDE runs may be
/// recorded as `emulated`. They never enable dispatch").
pub const VALIDATING_EXECUTORS: &[&str] = &["native", "rosetta2"];

/// Whether results from `executor` may validate a model
/// ([`VALIDATING_EXECUTORS`]; fail closed on any other name).
pub fn executor_may_validate(executor: &str) -> bool {
    VALIDATING_EXECUTORS.contains(&executor)
}

fn parse_host_entries(hosts: &[Json]) -> Vec<HostEntry> {
    hosts
        .iter()
        .filter_map(|h| {
            let s = |k: &str| h.get(k).and_then(Json::as_str).map(str::to_string);
            let n = |k: &str| h.get(k).and_then(Json::as_u64).unwrap_or(0);
            Some(HostEntry {
                cpu_key: s("cpu_key")?,
                executor: s("executor").unwrap_or_else(|| "unknown".into()),
                source_hash: s("source_hash")?,
                status: Status::parse(&s("status")?)?,
                random_cases: n("random_cases"),
                corner_cases: n("corner_cases"),
                mismatches: n("mismatches"),
            })
        })
        .collect()
}

