//! Evidence records: model source hashes × hardware campaign results
//! (DESIGN.md §9.2 "Validation (fail closed)").
//!
//! For each architecture the repository holds `evidence/<arch>.json`. Every
//! model of [`crate::registry`] has a record with
//!
//! * `source_hash` — SHA-256 ([`crate::fips::sha256`]) of the normalized text
//!   of the model's source items ([`model_hash`]): the model function and every
//!   helper and representation type it uses. An item's text runs from `pub fn`
//!   / `pub type` to the end of the item (doc comments are outside it) and is
//!   normalized to its Rust token stream ([`tokens`]): whitespace, layout and
//!   comments do not affect the hash, every token (including literals) does.
//! * `status` — `validated` (compared with the real intrinsic, ≥ 10^7 random
//!   cases + corners + every immediate, zero mismatches), `pending-hardware`
//!   (the CPU running the campaign lacks the feature; only the FIPS 180-4
//!   consistency checks ran — SHA-NI on this machine) or `failed`.
//! * the campaign counts, seed, and the FIPS consistency counts for SHA models;
//! * `core` — the model's **core-text transcription** (`core/<arch>.core`,
//!   [`crate::coretext`]): its global, its core items (the global and the
//!   helpers it uses), `core_hash` ([`crate::coretext::core_hash`], SHA-256 of
//!   their comment-free, whitespace-normalized text) and the counts of the
//!   **kernel cross-check** (`crate::kernel`, feature `kernel`): kernel
//!   evaluation of the core global == the executable model on
//!   ≥ [`REQUIRED_KERNEL_RANDOM_CASES`] random inputs + corners + every
//!   immediate;
//!
//! and the file records the machine (`sysctl machdep.cpu.brand_string`,
//! whether the process ran under Rosetta 2), the `rustc` version and target,
//! the build profile and the date.
//!
//! The top-level `kernel_crosscheck` object records the kernel campaign
//! (toolchain, date, a hash of the kernel prelude it ran against, and the
//! core-text compression cross-checks of `kernel::compress_checks`).
//!
//! **Fail closed.** [`validation`] answers "may emitted code execute this
//! instruction on this architecture?": only when the record exists, its hash
//! equals the hash of the model as compiled now, its status is `validated`
//! with zero mismatches and at least [`REQUIRED_RANDOM_CASES`] random cases,
//! **and** its core record is current (its `core_hash` equals the core text
//! as compiled now) with a passing kernel cross-check. Proofs are about the
//! core model, so the chain hardware ↔ Rust model ↔ core model must hold.
//! A stale record (model or core text edited after the campaign) counts as
//! missing. The dispatcher (§9.3) must not select a variant using a model
//! without it.
//!
//! Records are regenerated by the `sandblaster-targets-evidence` binary (the
//! core sections by `--core-only`, built with `--features kernel`).
//!
//! **Per-CPU keying (schema 3, design §19.1).** Every hardware campaign is
//! recorded under the key of the CPU it ran on ([`cpu::CpuId::key_on`]:
//! CPUID vendor/family/model/stepping, microcode, and the executor when not
//! native). Each model carries `hosts`: one entry per key with the model
//! hash the campaign ran against, its status and counts; the top-level
//! `hosts` array describes each machine, and `kats` holds the known-answer
//! tests of the feature-only scalar sets ([`kat`]). A new campaign
//! **merges** into the existing file ([`merge_hosts`]): entries of other
//! keys are kept (a v2 record becomes one `legacy:` host entry), the entry
//! of the campaign's own key is replaced, and each model's top-level
//! `status` is recomputed from its entries whose hash is current. The
//! verdict ([`validation_in`]) is then fail-closed across hosts: a current
//! failure on any CPU → not validated; otherwise validated if some CPU has a
//! current validated entry (≥ [`REQUIRED_RANDOM_CASES`], zero mismatches),
//! with the core record current as before. [`validation_on`] answers the
//! same question for one CPU key (per-microarchitecture reporting). Only results
//! of an executor in [`VALIDATING_EXECUTORS`] (native hardware, Rosetta 2)
//! count; anything else, including an unknown name, is recorded and never
//! validates. A schema-3 model without host entries has no evidence.
//! Whole records — one host kit output per CPU — are combined with
//! [`merge_files`] (never by copying one over another, which would drop
//! the other CPUs' results, failures included).
//!
//! The records are inputs of this crate's build (`build.rs` declares
//! `evidence/`), so a build script that consults them (the verified
//! pipeline) re-runs when they change.

