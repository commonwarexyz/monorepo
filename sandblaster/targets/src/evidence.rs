/// The outcome of one KAT ([`kat::KatSpec`]) on the campaign machine.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct KatOutcome {
    /// The KAT name ([`kat::KatSpec::name`]).
    pub name: String,
    /// Its feature.
    pub feature: String,
    /// Known answers checked (0 if skipped).
    pub known_answers: u64,
    /// Known answers that disagreed.
    pub known_failures: u64,
    /// The random differential phase against the reference (corner and
    /// random cases, mismatches), or a skipped outcome.
    pub differential: Outcome,
    /// `true` for a forced diagnostic run on a CPU that does not report the
    /// feature (never evidence).
    pub forced: bool,
}

impl KatOutcome {
    /// Every known answer and differential case agreed, and something ran.
    pub fn passed(&self) -> bool {
        self.differential.skipped.is_none() && self.known_failures == 0 && self.known_answers > 0 && self.differential.passed()
    }

    /// `passed`, `failed`, `skipped` or `diagnostic`.
    pub fn status(&self) -> &'static str {
        if self.forced {
            "diagnostic"
        } else if self.differential.skipped.is_some() {
            "skipped"
        } else if self.passed() {
            "passed"
        } else {
            "failed"
        }
    }
}

fn kat_json(o: &KatOutcome, cpu_key: &str, hash: &str) -> Json {
    let spec = kat::find(&o.name);
    let mut m: Vec<(String, Json)> = vec![
        ("cpu_key".into(), Json::str(cpu_key)),
        ("name".into(), Json::str(o.name.clone())),
        ("feature".into(), Json::str(o.feature.clone())),
        ("set".into(), Json::str(kat::SET)),
        (
            "instructions".into(),
            Json::Arr(spec.map_or(&[][..], |s| s.instructions).iter().map(|i| Json::str(*i)).collect()),
        ),
        ("kat_hash".into(), Json::str(hash)),
        ("status".into(), Json::str(o.status())),
        ("known_answers".into(), Json::uint(o.known_answers)),
        ("known_failures".into(), Json::uint(o.known_failures)),
    ];
    if let Json::Obj(c) = outcome_counts(&o.differential) {
        m.extend(c);
    }
    if let Some(r) = &o.differential.skipped {
        m.push(("skipped".into(), Json::str(r.clone())));
    }
    if let Some(f) = &o.differential.first_mismatch {
        m.push(("first_mismatch".into(), Json::str(f.clone())));
    }
    Json::Obj(m)
}

/// Record KAT outcomes of the campaign machine `cpu_key` in `doc`: its
/// previous KAT entries (same key) are replaced, other keys' kept.
pub fn with_kats(doc: &mut Json, outcomes: &[KatOutcome], cpu_key: &str) {
    let hash = kat::kat_hash();
    let mut kats: Vec<Json> = doc
        .get("kats")
        .and_then(Json::as_array)
        .unwrap_or(&[])
        .iter()
        .filter(|k| k.get("cpu_key").and_then(Json::as_str) != Some(cpu_key))
        .cloned()
        .collect();
    kats.extend(outcomes.iter().map(|o| kat_json(o, cpu_key, &hash)));
    set_member(doc, "kats", Json::Arr(kats));
}

