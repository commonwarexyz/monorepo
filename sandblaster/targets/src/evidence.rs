/// The per-model host entries and host summaries of an existing document.
/// A schema-2 document (no `hosts`) yields one `legacy:` entry per model
/// from its single campaign.
fn old_hosts(old: &Json) -> (Vec<(String, Json)>, Vec<Json>) {
    let mut entries = Vec::new();
    let models = old.get("models").and_then(Json::as_array).unwrap_or(&[]);
    let has_hosts = old.get("hosts").is_some();
    let legacy = || {
        let m = old.get("machine");
        let s = |k: &str| m.and_then(|m| m.get(k)).and_then(Json::as_str).unwrap_or("unknown").to_string();
        legacy_key(&s("cpu_brand_string"), &s("executor"))
    };
    for m in models {
        let Some(name) = m.get("name").and_then(Json::as_str) else { continue };
        if has_hosts {
            for h in m.get("hosts").and_then(Json::as_array).unwrap_or(&[]) {
                entries.push((name.to_string(), h.clone()));
            }
        } else {
            // schema 2: the model's top-level status and hardware counts
            let hw = m.get("hardware");
            let mut e: Vec<(String, Json)> = vec![
                ("cpu_key".into(), Json::str(legacy())),
                (
                    "executor".into(),
                    Json::str(old.get("machine").and_then(|x| x.get("executor")).and_then(Json::as_str).unwrap_or("unknown")),
                ),
                ("date".into(), old.get("date").cloned().unwrap_or(Json::Null)),
                ("rustc".into(), old.get("rustc").cloned().unwrap_or(Json::Null)),
                ("source_hash".into(), m.get("source_hash").cloned().unwrap_or(Json::Null)),
                ("status".into(), m.get("status").cloned().unwrap_or(Json::str("failed"))),
            ];
            for k in ["random_cases", "corner_cases", "mismatches", "seed", "skipped", "first_mismatch"] {
                if let Some(v) = hw.and_then(|h| h.get(k)) {
                    e.push((k.into(), v.clone()));
                }
            }
            entries.push((name.to_string(), Json::Obj(e)));
        }
    }
    let summaries = match old.get("hosts").and_then(Json::as_array) {
        Some(h) => h.to_vec(),
        None if old.get("machine").is_some() => vec![Json::obj([
            ("cpu_key", Json::str(legacy())),
            ("machine", old.get("machine").cloned().unwrap_or(Json::Null)),
            ("target", old.get("target").cloned().unwrap_or(Json::Null)),
            ("rustc", old.get("rustc").cloned().unwrap_or(Json::Null)),
            ("profile", old.get("profile").cloned().unwrap_or(Json::Null)),
            ("date", old.get("date").cloned().unwrap_or(Json::Null)),
            (
                "random_cases_per_model",
                old.get("campaign").and_then(|c| c.get("random_cases_per_model")).cloned().unwrap_or(Json::Null),
            ),
        ])],
        None => Vec::new(),
    };
    (entries, summaries)
}

fn host_key(j: &Json) -> Option<&str> {
    j.get("cpu_key").and_then(Json::as_str)
}

/// Merge the host entries, host summaries and KATs of `old` (an earlier
/// evidence document of the same architecture, schema 2 or 3) into the
/// freshly rendered `doc`, whose own campaign key wins, and recompute each
/// model's top-level `status` from its entries whose model hash is current
/// ([`merged_status`]). Entries of models that no longer exist are dropped.
pub fn merge_hosts(doc: &mut Json, old: &Json) {
    let Some(arch) = doc.get("arch").and_then(Json::as_str).and_then(Arch::from_name) else { return };
    if old.get("arch").and_then(Json::as_str) != Some(arch.name()) {
        return;
    }
    let new_key = doc.get("cpu_key").and_then(Json::as_str).unwrap_or_default().to_string();
    let (entries, summaries) = old_hosts(old);
    if let Some(models) = models_mut(doc) {
        for m in models.iter_mut() {
            let Some(name) = m.get("name").and_then(Json::as_str).map(str::to_string) else { continue };
            let mut hosts: Vec<Json> = m.get("hosts").and_then(Json::as_array).unwrap_or(&[]).to_vec();
            for (n, e) in &entries {
                if *n == name && host_key(e) != Some(new_key.as_str()) && !hosts.iter().any(|h| host_key(h) == host_key(e)) {
                    hosts.push(e.clone());
                }
            }
            if let Some(model) = crate::registry::find(arch, &name) {
                let status = merged_status(&parse_host_entries(&hosts), &model_hash(model));
                set_member(m, "status", Json::str(status.as_str()));
            }
            set_member(m, "hosts", Json::Arr(hosts));
        }
    }
    let mut hosts: Vec<Json> = doc.get("hosts").and_then(Json::as_array).unwrap_or(&[]).to_vec();
    for s in summaries {
        if host_key(&s) != Some(new_key.as_str()) && !hosts.iter().any(|h| host_key(h) == host_key(&s)) {
            hosts.push(s);
        }
    }
    set_member(doc, "hosts", Json::Arr(hosts));
    let mut kats: Vec<Json> = doc.get("kats").and_then(Json::as_array).unwrap_or(&[]).to_vec();
    for k in old.get("kats").and_then(Json::as_array).unwrap_or(&[]) {
        if host_key(k) != Some(new_key.as_str()) {
            kats.push(k.clone());
        }
    }
    set_member(doc, "kats", Json::Arr(kats));
}

/// The fail-closed status over a model's host entries whose `source_hash`
/// is `current`: `failed` if any failed (or recorded a mismatch); else
/// `validated` if any was compared with hardware without a mismatch (the
/// verdict [`validation_in`] additionally requires ≥
/// [`REQUIRED_RANDOM_CASES`] random cases); else `pending-hardware` if any
/// is pending; else `failed` (nothing current).
pub fn merged_status(hosts: &[HostEntry], current: &str) -> Status {
    let cur: Vec<&HostEntry> = hosts.iter().filter(|h| h.source_hash == current).collect();
    if cur.iter().any(|h| h.status == Status::Failed || h.mismatches != 0) {
        Status::Failed
    } else if cur.iter().any(|h| h.status == Status::Validated) {
        Status::Validated
    } else if cur.iter().any(|h| h.status == Status::PendingHardware) {
        Status::PendingHardware
    } else {
        Status::Failed
    }
}

