/// Status of one model's evidence.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Status {
    /// Compared with the real intrinsic; zero mismatches.
    Validated,
    /// Feature absent on the campaign machine; FIPS consistency only.
    PendingHardware,
    /// A mismatch was found (the model or the harness is wrong).
    Failed,
}

impl Status {
    /// The JSON spelling.
    pub fn as_str(self) -> &'static str {
        match self {
            Status::Validated => "validated",
            Status::PendingHardware => "pending-hardware",
            Status::Failed => "failed",
        }
    }

    /// Parse the JSON spelling.
    pub fn parse(s: &str) -> Option<Status> {
        match s {
            "validated" => Some(Status::Validated),
            "pending-hardware" => Some(Status::PendingHardware),
            "failed" => Some(Status::Failed),
            _ => None,
        }
    }
}

fn outcome_counts(o: &Outcome) -> Json {
    Json::obj([
        ("random_cases", Json::uint(o.random)),
        ("corner_cases", Json::uint(o.corner)),
        ("mismatches", Json::uint(o.mismatches)),
        ("seed", Json::str(format!("{:#018x}", o.seed))),
    ])
}

/// The status a hardware outcome and consistency outcome imply.
pub fn status_of(hw: &Outcome, consistency: Option<&Outcome>) -> Status {
    let consistency_ok = consistency.is_none_or(Outcome::passed);
    if hw.skipped.is_some() {
        return if consistency.is_some() && consistency_ok {
            Status::PendingHardware
        } else {
            Status::Failed
        };
    }
    if hw.passed() && consistency_ok {
        Status::Validated
    } else {
        Status::Failed
    }
}

/// Build the evidence document for `arch` from the campaign outcomes.
///
/// `hardware` holds one outcome per registry model (named after it, skipped
/// when the feature is absent); `consistency` holds the FIPS consistency
/// outcomes (per-model ones share the model's name; the rest are listed under
/// `compositions`), and `hardware_compositions` the whole-kernel hardware
/// checks (e.g. the real-intrinsics compression against FIPS).
pub fn render(
    arch: Arch,
    machine: &Machine,
    cfg: &Config,
    hardware: &[Outcome],
    consistency: &[Outcome],
    hardware_compositions: &[Outcome],
) -> Json {
    let mut models = Vec::new();
    for model in arch.models() {
        let hw = hardware
            .iter()
            .find(|o| o.name == model.name)
            .cloned()
            .unwrap_or_else(|| Outcome::skipped(model.name, "no campaign ran"));
        let cons = consistency.iter().find(|o| o.name == model.name);
        let status = status_of(&hw, cons);
        let mut fields: Vec<(String, Json)> = vec![
            ("name".into(), Json::str(model.name)),
            ("rust_path".into(), Json::str(model.rust_path)),
            ("instruction".into(), Json::str(model.instruction)),
            (
                "features".into(),
                Json::Arr(model.features.iter().map(|f| Json::str(*f)).collect()),
            ),
            (
                "source_items".into(),
                Json::Arr(
                    model
                        .items
                        .iter()
                        .map(|i| Json::str(format!("{}::{}", i.source.path(), i.name)))
                        .collect(),
                ),
            ),
            ("source_hash".into(), Json::str(model_hash(model))),
            ("status".into(), Json::str(status.as_str())),
        ];
        let hw_json = match &hw.skipped {
            Some(reason) => Json::obj([
                (
                    "method",
                    Json::str(format!("differential vs {}", model.rust_path)),
                ),
                ("skipped", Json::str(reason.clone())),
            ]),
            None => {
                let mut o = match outcome_counts(&hw) {
                    Json::Obj(m) => m,
                    _ => unreachable!(),
                };
                o.insert(
                    0,
                    (
                        "method".into(),
                        Json::str(format!(
                            "differential vs {} on {}",
                            model.rust_path, machine.executor
                        )),
                    ),
                );
                o.push((
                    "immediates".into(),
                    match &hw.immediates {
                        Some(r) => Json::str(format!("{}..={} (exhaustive)", r.start(), r.end())),
                        None => Json::Null,
                    },
                ));
                if let Some(m) = &hw.first_mismatch {
                    o.push(("first_mismatch".into(), Json::str(m.clone())));
                }
                Json::Obj(o)
            }
        };
        fields.push(("hardware".into(), hw_json));
        fields.push(("hosts".into(), Json::Arr(vec![host_entry_json(machine, &model_hash(model), status, &hw)])));
        if let Some(c) = cons {
            let mut o = match outcome_counts(c) {
                Json::Obj(m) => m,
                _ => unreachable!(),
            };
            o.insert(
                0,
                (
                    "property".into(),
                    Json::str(consistency_property(model.name)),
                ),
            );
            // The 256/512-bit models are checked against an independent
            // reference implementation, the SHA models against FIPS 180-4.
            let key = if crate::reference::NAMES.contains(&model.name) { "reference_consistency" } else { "fips180_4_consistency" };
            fields.push((key.into(), Json::Obj(o)));
        }
        if status == Status::PendingHardware {
            fields.push((
                "note".into(),
                Json::str("hardware validation pending: the campaign CPU lacks this feature; run the evidence binary on a CPU with it (x86 CI)"),
            ));
        }
        models.push(Json::Obj(fields));
    }
    let compositions: Vec<Json> = consistency
        .iter()
        .filter(|o| arch.models().iter().all(|m| m.name != o.name))
        .map(|o| composition_json(o, "model consistency (portable)"))
        .chain(
            hardware_compositions
                .iter()
                .map(|o| composition_json(o, "real intrinsics (hardware)")),
        )
        .collect();
    Json::obj([
        ("schema", Json::str(SCHEMA)),
        ("arch", Json::str(arch.name())),
        ("target", Json::str(machine.target.clone())),
        ("cpu_key", Json::str(machine.cpu_key())),
        ("machine", machine_json(machine)),
        ("rustc", Json::str(machine.rustc.clone())),
        ("profile", Json::str(machine.profile.clone())),
        ("date", Json::str(machine.date.clone())),
        (
            "campaign",
            Json::obj([
                ("random_cases_per_model", Json::uint(cfg.random_per_model)),
                ("base_seed", Json::str(format!("{:#018x}", cfg.seed))),
                (
                    "corner_values",
                    Json::str(
                        "per argument: 0, ~0, 0x8000_0000, 1, 0x7fff_ffff, every single-bit word, byte patterns; lanes drawn from corners with p = 1/8 in the random phase",
                    ),
                ),
                (
                    "required_random_cases_for_validated",
                    Json::uint(REQUIRED_RANDOM_CASES),
                ),
            ]),
        ),
        ("models", Json::Arr(models)),
        ("compositions", Json::Arr(compositions)),
        ("hosts", Json::Arr(vec![host_summary_json(machine, cfg)])),
        ("kats", Json::Arr(Vec::new())),
    ])
}

