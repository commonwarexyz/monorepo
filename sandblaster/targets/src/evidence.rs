/// A document in schema-3 form: a schema-3 document unchanged; an older one
/// with its single campaign turned into one `legacy:` host entry per model
/// and one host summary (as [`merge_hosts`] records it).
fn as_v3(doc: &Json) -> Json {
    if doc.get("schema").and_then(Json::as_str) == Some(SCHEMA) {
        return doc.clone();
    }
    let (entries, summaries) = old_hosts(doc);
    let legacy = summaries.first().and_then(host_key).unwrap_or("legacy:unknown (unknown)").to_string();
    let mut d = doc.clone();
    set_member(&mut d, "schema", Json::str(SCHEMA));
    set_member(&mut d, "cpu_key", Json::str(legacy));
    if let Some(models) = models_mut(&mut d) {
        for m in models.iter_mut() {
            let Some(name) = m.get("name").and_then(Json::as_str).map(str::to_string) else { continue };
            let hs: Vec<Json> = entries.iter().filter(|(n, _)| *n == name).map(|(_, e)| e.clone()).collect();
            set_member(m, "hosts", Json::Arr(hs));
        }
    }
    set_member(&mut d, "hosts", Json::Arr(summaries));
    if d.get("kats").is_none() {
        set_member(&mut d, "kats", Json::Arr(Vec::new()));
    }
    d
}

/// Whether an entry records a failure: status `failed`, or any mismatch.
fn records_failure(e: &Json) -> bool {
    e.get("status").and_then(Json::as_str) == Some("failed")
        || e.get("mismatches").and_then(Json::as_u64).unwrap_or(0) != 0
        || e.get("known_failures").and_then(Json::as_u64).unwrap_or(0) != 0
}

/// Notes and conflicts of a [`merge_files`] run.
#[derive(Default)]
struct MergeLog {
    notes: Vec<String>,
    conflicts: Vec<String>,
}

/// Union of two lists of per-CPU entries, identified by `id` (the CPU key,
/// plus the KAT name for KATs). `base_owner` / `other_owner` are the CPU
/// keys whose campaign produced each document (its `cpu_key`).
///
/// * an entry only one side has is kept;
/// * identical entries are kept once;
/// * differing entries of the same id: the side whose own campaign ran on
///   that CPU wins (the other side carries an older copy), unless that would
///   drop a recorded failure for the same model or KAT table (`hash_key`) —
///   then, and whenever neither or both sides own the CPU, it is a conflict.
///   Failures are never dropped silently (fail closed across CPUs).
fn union_entries(
    base: &mut Vec<Json>,
    other: &[Json],
    id: &dyn Fn(&Json) -> Option<String>,
    hash_key: &str,
    owners: (&str, &str),
    what: &str,
    log: &mut MergeLog,
) {
    let (base_owner, other_owner) = owners;
    let MergeLog { notes, conflicts } = log;
    for e in other {
        let Some(k) = id(e) else {
            conflicts.push(format!("{what}: an entry without `cpu_key`"));
            continue;
        };
        let Some(i) = base.iter().position(|b| id(b).as_deref() == Some(k.as_str())) else {
            base.push(e.clone());
            continue;
        };
        if base[i] == *e {
            continue;
        }
        let cpu = host_key(e).unwrap_or_default();
        let same_hash = base[i].get(hash_key) == e.get(hash_key);
        let (winner_is_other, loser) = match (cpu == base_owner, cpu == other_owner) {
            (false, true) => (true, &base[i]),
            (true, false) => (false, e),
            _ => {
                conflicts.push(format!("{what}: both records hold different results for {k} and neither's own campaign is the newer one; merge by hand or re-run that CPU"));
                continue;
            }
        };
        let winner = if winner_is_other { e } else { &base[i] };
        if same_hash && records_failure(loser) && !records_failure(winner) {
            conflicts.push(format!("{what}: the campaign of {cpu} passes where the other record keeps a failure of it; refusing to drop a failure (re-run that CPU or edit by hand)"));
            continue;
        }
        notes.push(format!("{what}: kept the latest campaign of {k}"));
        if winner_is_other {
            base[i] = e.clone();
        }
    }
}

/// Merge the evidence document `other` into `base` (both of the same
/// architecture): the `--merge-files` of the evidence binary, which combines
/// the kit outputs of several hosts (each one the committed record plus its
/// own CPU's entries) without dropping any CPU's result.
///
/// Per model, per KAT and per host summary the entries are united by CPU
/// key (`union_entries`: a CPU's own campaign wins over an older carried
/// copy; a same-key disagreement otherwise, or one that would drop a
/// recorded failure, is a conflict). A model's top-level fields and core
/// record come from whichever side is current for the model as compiled
/// now; its `status` is recomputed ([`merged_status`]). `base` keeps its
/// `cpu_key`, `machine` and `kernel_crosscheck` (taken from `other` if
/// `base` has none). Older schemas are read as one `legacy:` host. On a
/// conflict nothing is merged and every conflict is returned; otherwise the
/// notes (which carried copies were superseded).
pub fn merge_files(base: &mut Json, other: &Json) -> Result<Vec<String>, Vec<String>> {
    let arch_of = |d: &Json| d.get("arch").and_then(Json::as_str).and_then(Arch::from_name);
    let (Some(arch), Some(oarch)) = (arch_of(base), arch_of(other)) else {
        return Err(vec!["a record without a known `arch`".into()]);
    };
    if arch != oarch {
        return Err(vec![format!("records of different architectures ({} and {})", arch.name(), oarch.name())]);
    }
    let mut merged = as_v3(base);
    let other = as_v3(other);
    let owners_s = (
        merged.get("cpu_key").and_then(Json::as_str).unwrap_or_default().to_string(),
        other.get("cpu_key").and_then(Json::as_str).unwrap_or_default().to_string(),
    );
    let owners = (owners_s.0.as_str(), owners_s.1.as_str());
    let mut log = MergeLog::default();
    let by_key = |j: &Json| host_key(j).map(str::to_string);
    let other_models = other.get("models").and_then(Json::as_array).unwrap_or(&[]).to_vec();
    if let Some(models) = models_mut(&mut merged) {
        for om in &other_models {
            let Some(name) = om.get("name").and_then(Json::as_str) else { continue };
            match models.iter_mut().find(|m| m.get("name").and_then(Json::as_str) == Some(name)) {
                None => models.push(om.clone()),
                Some(bm) => {
                    let mut hosts: Vec<Json> = bm.get("hosts").and_then(Json::as_array).unwrap_or(&[]).to_vec();
                    let oh = om.get("hosts").and_then(Json::as_array).unwrap_or(&[]);
                    union_entries(&mut hosts, oh, &by_key, "source_hash", owners, &format!("model {name}"), &mut log);
                    if let Some(model) = crate::registry::find(arch, name) {
                        let current = model_hash(model);
                        let is_current = |m: &Json| m.get("source_hash").and_then(Json::as_str) == Some(current.as_str());
                        if !is_current(bm) && is_current(om) {
                            *bm = om.clone();
                        }
                        let core_current = |m: &Json| {
                            let want = coretext::find(arch, name).map(|c| c.hash());
                            want.is_some() && m.get("core").and_then(|c| c.get("core_hash")).and_then(Json::as_str) == want.as_deref()
                        };
                        if !core_current(bm) && core_current(om) {
                            set_member(bm, "core", om.get("core").cloned().unwrap_or(Json::Null));
                        }
                        set_member(bm, "status", Json::str(merged_status(&parse_host_entries(&hosts), &current).as_str()));
                    }
                    set_member(bm, "hosts", Json::Arr(hosts));
                }
            }
        }
    }
    let mut kats: Vec<Json> = merged.get("kats").and_then(Json::as_array).unwrap_or(&[]).to_vec();
    let kat_id = |j: &Json| Some(format!("{} {}", host_key(j)?, j.get("name").and_then(Json::as_str)?));
    let okats = other.get("kats").and_then(Json::as_array).unwrap_or(&[]);
    union_entries(&mut kats, okats, &kat_id, "kat_hash", owners, "KAT", &mut log);
    set_member(&mut merged, "kats", Json::Arr(kats));
    let mut sets: Vec<Json> = merged.get("sets").and_then(Json::as_array).unwrap_or(&[]).to_vec();
    let set_id = |j: &Json| Some(format!("{} {} {}", host_key(j)?, j.get("set").and_then(Json::as_str)?, j.get("suite").and_then(Json::as_str)?));
    let osets = other.get("sets").and_then(Json::as_array).unwrap_or(&[]);
    union_entries(&mut sets, osets, &set_id, "set_hash", owners, "set run", &mut log);
    if !sets.is_empty() {
        set_member(&mut merged, "sets", Json::Arr(sets));
    }
    // Host summaries describe machines, not results: the owner's copy wins,
    // otherwise the base's is kept.
    let mut hosts: Vec<Json> = merged.get("hosts").and_then(Json::as_array).unwrap_or(&[]).to_vec();
    for s in other.get("hosts").and_then(Json::as_array).unwrap_or(&[]) {
        match hosts.iter().position(|h| host_key(h) == host_key(s)) {
            None => hosts.push(s.clone()),
            Some(i) if host_key(s) == Some(owners.1) && host_key(s) != Some(owners.0) => hosts[i] = s.clone(),
            Some(_) => {}
        }
    }
    set_member(&mut merged, "hosts", Json::Arr(hosts));
    if merged.get("kernel_crosscheck").is_none()
        && let Some(k) = other.get("kernel_crosscheck")
    {
        set_member(&mut merged, "kernel_crosscheck", k.clone());
    }
    if !log.conflicts.is_empty() {
        return Err(log.conflicts);
    }
    *base = merged;
    log.notes.sort();
    log.notes.dedup();
    Ok(log.notes)
}

fn composition_json(o: &Outcome, kind: &str) -> Json {
    let mut m = match outcome_counts(o) {
        Json::Obj(m) => m,
        _ => unreachable!(),
    };
    m.insert(0, ("name".into(), Json::str(o.name.clone())));
    m.insert(1, ("kind".into(), Json::str(kind)));
    if let Some(reason) = &o.skipped {
        m.push(("skipped".into(), Json::str(reason.clone())));
    }
    if let Some(mm) = &o.first_mismatch {
        m.push(("first_mismatch".into(), Json::str(mm.clone())));
    }
    Json::Obj(m)
}

fn consistency_property(name: &str) -> &'static str {
    match name {
        "vsha256hq_u32" => {
            "vsha256hq_u32(abcd, efgh, wk) == abcd half of 4 FIPS 180-4 rounds with K+W = wk"
        }
        "vsha256h2q_u32" => {
            "vsha256h2q_u32(efgh, abcd_pre, wk) == efgh half of the same 4 FIPS rounds"
        }
        "vsha256su0q_u32" => "vsha256su0q_u32(W0..3, W4..7)[i] == W_i + sigma0(W_{i+1})",
        "vsha256su1q_u32" => {
            "vsha256su1q_u32(x, W8..11, W12..15) == FIPS schedule tail (W16..W19 given x = su0 part)"
        }
        "_mm_sha256rnds2_epu32" => {
            "_mm_sha256rnds2_epu32(cdgh, abef, wk) == 2 FIPS rounds with wk[0], wk[1] on the ABEF/CDGH packing"
        }
        "_mm_sha256msg1_epu32" => "_mm_sha256msg1_epu32(W0..3, W4..7)[i] == W_i + sigma0(W_{i+1})",
        "_mm_sha256msg2_epu32" => {
            "_mm_sha256msg2_epu32(x, W12..15) == FIPS schedule tail (W16..W19 given x)"
        }
        n if crate::reference::NAMES.contains(&n) => {
            "executable model == the independent reference implementation (src/reference.rs), corners + random + every immediate"
        }
        _ => "FIPS 180-4 consistency",
    }
}

