/// A parsed evidence file.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct EvidenceFile {
    /// The schema identifier ([`SCHEMA`], [`SCHEMA_V2`] or [`SCHEMA_V1`]).
    pub schema: String,
    /// Architecture.
    pub arch: Arch,
    /// CPU brand string of the campaign machine.
    pub cpu_brand_string: String,
    /// `native` or `rosetta2`.
    pub executor: String,
    /// `rustc -V`.
    pub rustc: String,
    /// Campaign date.
    pub date: String,
    /// Per-model records.
    pub records: Vec<Record>,
    /// The CPU key of the latest campaign (schema 3), or a `legacy:` key.
    pub cpu_key: String,
    /// Every campaign machine (schema 3; one legacy entry for older files).
    pub hosts: Vec<HostSummary>,
    /// Known-answer tests (schema 3).
    pub kats: Vec<KatRecord>,
    /// Host runs of feature-only variant sets (schema 3, optional:
    /// [`SetRecord`]).
    pub sets: Vec<SetRecord>,
}

/// One set run of an evidence document, read strictly: the run gates code
/// generation, so a field of the wrong type is an error for the whole file
/// (fail closed, as for a malformed model host entry), never a default.
/// `cases` and `mismatches` must be unsigned integers, `features` and
/// `unreported_features` arrays of strings, `status` one of `passed`,
/// `failed`, `skipped`, `diagnostic`, `set_hash` the [`set_hash`] of `set`
/// and `features`, and every unreported feature one of `features`.
fn parse_set_record(r: &Json) -> Result<SetRecord, String> {
    let s = |k: &str| r.get(k).and_then(Json::as_str).map(str::to_string).ok_or_else(|| format!("set run without the string field `{k}`"));
    let (cpu_key, set, suite) = (s("cpu_key")?, s("set")?, s("suite")?);
    let at = format!("set run `{set}` {suite} on {cpu_key}");
    let n = |k: &str| r.get(k).and_then(Json::as_u64).ok_or_else(|| format!("{at}: `{k}` is not an unsigned integer"));
    let strings = |k: &str| -> Result<Vec<String>, String> {
        let bad = || format!("{at}: `{k}` is not an array of strings");
        r.get(k).and_then(Json::as_array).ok_or_else(bad)?.iter().map(|j| j.as_str().map(str::to_string).ok_or_else(bad)).collect()
    };
    let status = s("status")?;
    if !SET_STATUSES.contains(&status.as_str()) {
        return Err(format!("{at}: unknown status `{status}`"));
    }
    let features = strings("features")?;
    let set_hash_text = s("set_hash")?;
    if set_hash_text != set_hash(&set, &features) {
        return Err(format!("{at}: `set_hash` is not the hash of the set's name and `features`"));
    }
    let unreported = strings("unreported_features")?;
    if let Some(f) = unreported.iter().find(|f| !features.contains(f)) {
        return Err(format!("{at}: unreported feature `{f}` is not one of the set's features"));
    }
    Ok(SetRecord {
        executor: r.get("executor").and_then(Json::as_str).unwrap_or("unknown").to_string(),
        cases: n("cases")?,
        mismatches: n("mismatches")?,
        cpu_key,
        set,
        set_hash: set_hash_text,
        suite,
        status,
        unreported,
    })
}

/// Parse an evidence document.
pub fn parse(text: &str) -> Result<EvidenceFile, String> {
    let doc = json::parse(text).map_err(|e| e.to_string())?;
    let field = |j: &Json, k: &str| -> Result<String, String> {
        j.get(k)
            .and_then(Json::as_str)
            .map(str::to_string)
            .ok_or_else(|| format!("missing string field `{k}`"))
    };
    let schema = field(&doc, "schema")?;
    if schema != SCHEMA && schema != SCHEMA_V2 && schema != SCHEMA_V1 {
        return Err(format!("unknown schema `{schema}` (expected {SCHEMA})"));
    }
    let arch = Arch::from_name(&field(&doc, "arch")?).ok_or("unknown arch")?;
    let machine = doc.get("machine").ok_or("missing `machine`")?;
    let v3 = schema == SCHEMA;
    if v3 {
        for k in ["cpu_key", "hosts", "kats"] {
            if doc.get(k).is_none() {
                return Err(format!("schema 3 document without `{k}`"));
            }
        }
    }
    let mut records = Vec::new();
    for m in doc
        .get("models")
        .and_then(Json::as_array)
        .ok_or("missing `models`")?
    {
        let status_text = field(m, "status")?;
        let hw = m.get("hardware");
        let count = |k: &str| {
            hw.and_then(|h| h.get(k))
                .and_then(Json::as_u64)
                .unwrap_or(0)
        };
        records.push(Record {
            name: field(m, "name")?,
            source_hash: field(m, "source_hash")?,
            status: Status::parse(&status_text)
                .ok_or_else(|| format!("unknown status `{status_text}`"))?,
            random_cases: count("random_cases"),
            corner_cases: count("corner_cases"),
            mismatches: count("mismatches"),
            core: m.get("core").and_then(parse_core),
            hosts: if v3 {
                let hs = m.get("hosts").and_then(Json::as_array).ok_or("schema 3 model without `hosts`")?;
                let parsed = parse_host_entries(hs);
                if parsed.len() != hs.len() {
                    return Err(format!("{}: malformed host entry", field(m, "name")?));
                }
                parsed
            } else {
                Vec::new()
            },
        });
    }
    let brand = field(machine, "cpu_brand_string")?;
    let executor = field(machine, "executor")?;
    let cpu_key = if v3 { field(&doc, "cpu_key")? } else { legacy_key(&brand, &executor) };
    let hosts = match doc.get("hosts").and_then(Json::as_array) {
        Some(hs) => hs
            .iter()
            .map(|h| {
                let m = h.get("machine");
                let ms = |k: &str| m.and_then(|m| m.get(k)).and_then(Json::as_str).unwrap_or("").to_string();
                Ok(HostSummary {
                    cpu_key: field(h, "cpu_key")?,
                    cpu_brand_string: ms("cpu_brand_string"),
                    executor: ms("executor"),
                    cpu: m.and_then(|m| m.get("cpu")).and_then(cpu::CpuId::from_json),
                    detected_features: match m.and_then(|m| m.get("detected_features")) {
                        Some(Json::Obj(fs)) => fs.iter().map(|(f, on)| (f.clone(), on.as_bool() == Some(true))).collect(),
                        _ => Vec::new(),
                    },
                    date: h.get("date").and_then(Json::as_str).unwrap_or("").to_string(),
                })
            })
            .collect::<Result<Vec<_>, String>>()?,
        None => vec![HostSummary {
            cpu_key: cpu_key.clone(),
            cpu_brand_string: brand.clone(),
            executor: executor.clone(),
            cpu: None,
            detected_features: Vec::new(),
            date: field(&doc, "date")?,
        }],
    };
    let kats = doc
        .get("kats")
        .and_then(Json::as_array)
        .unwrap_or(&[])
        .iter()
        .map(|k| {
            let n = |key: &str| k.get(key).and_then(Json::as_u64).unwrap_or(0);
            Ok(KatRecord {
                cpu_key: field(k, "cpu_key")?,
                name: field(k, "name")?,
                feature: field(k, "feature")?,
                kat_hash: field(k, "kat_hash")?,
                status: field(k, "status")?,
                known_answers: n("known_answers"),
                random_cases: n("random_cases"),
                mismatches: n("mismatches") + n("known_failures"),
            })
        })
        .collect::<Result<Vec<_>, String>>()?;
    let sets = doc
        .get("sets")
        .and_then(Json::as_array)
        .unwrap_or(&[])
        .iter()
        .map(parse_set_record)
        .collect::<Result<Vec<_>, String>>()?;
    Ok(EvidenceFile {
        schema,
        arch,
        cpu_brand_string: brand,
        executor,
        rustc: field(&doc, "rustc")?,
        date: field(&doc, "date")?,
        records,
        cpu_key,
        hosts,
        kats,
        sets,
    })
}

fn parse_core(c: &Json) -> Option<CoreRecord> {
    let k = c.get("kernel_crosscheck");
    let count = |key: &str| k.and_then(|k| k.get(key)).and_then(Json::as_u64).unwrap_or(0);
    Some(CoreRecord {
        global: c.get("global")?.as_str()?.to_string(),
        core_hash: c.get("core_hash")?.as_str()?.to_string(),
        random_cases: count("random_cases"),
        corner_cases: count("corner_cases"),
        mismatches: count("mismatches"),
        immediates: k.and_then(|k| k.get("immediates")).and_then(Json::as_str).map(str::to_string),
        crosschecked: k.is_some_and(|k| k.get("skipped").is_none()),
    })
}

/// Load and parse the committed evidence file of `arch` (parsed once per
/// process while the file's size and modification time stay the same: the
/// optimizer's evidence gate asks for every intrinsic it prints).
pub fn load(arch: Arch) -> Result<EvidenceFile, String> {
    type Cached = (PathBuf, Option<std::time::SystemTime>, u64, EvidenceFile);
    static CACHE: std::sync::Mutex<Vec<Cached>> = std::sync::Mutex::new(Vec::new());
    let path = evidence_path(arch);
    let meta = std::fs::metadata(&path).ok();
    let (mtime, len) = (meta.as_ref().and_then(|m| m.modified().ok()), meta.as_ref().map_or(0, |m| m.len()));
    if meta.is_some()
        && let Some((_, _, _, f)) = CACHE.lock().unwrap_or_else(|e| e.into_inner()).iter().find(|(p, t, l, _)| *p == path && *t == mtime && *l == len)
    {
        return Ok(f.clone());
    }
    let f = load_uncached(arch, &path)?;
    let mut c = CACHE.lock().unwrap_or_else(|e| e.into_inner());
    c.retain(|(p, _, _, _)| *p != path);
    c.push((path, mtime, len, f.clone()));
    Ok(f)
}

fn load_uncached(arch: Arch, path: &std::path::Path) -> Result<EvidenceFile, String> {
    let path = path.to_path_buf();
    let text = std::fs::read_to_string(&path).map_err(|e| format!("{}: {e}", path.display()))?;
    let file = parse(&text).map_err(|e| format!("{}: {e}", path.display()))?;
    if file.arch != arch {
        return Err(format!(
            "{}: records arch {}",
            path.display(),
            file.arch.name()
        ));
    }
    Ok(file)
}

/// The fail-closed verdict for one model.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum Validation {
    /// Current, hardware-validated evidence (executor recorded).
    Validated {
        /// `native` or `rosetta2`.
        executor: String,
    },
    /// Current evidence, but only FIPS consistency (feature absent).
    PendingHardware,
    /// No usable evidence, with the reason.
    Missing(String),
}

/// The core-text half of a record: `Ok` iff the core record is current (its
/// hash equals the core text as compiled now) and its kernel cross-check
/// passed with at least [`REQUIRED_KERNEL_RANDOM_CASES`] random cases and
/// every immediate.
pub fn core_check(file_arch: Arch, rec: &Record, model: &Model) -> Result<(), String> {
    let name = &model.name;
    let Some(cm) = coretext::find(file_arch, name) else {
        return Err(format!("{name}: no core-text model"));
    };
    let Some(core) = &rec.core else {
        return Err(format!("{name}: no core record (run the evidence binary with --features kernel -- --core-only)"));
    };
    if core.global != cm.global {
        return Err(format!("{name}: core record names {} instead of {}", core.global, cm.global));
    }
    let current = cm.hash();
    if core.core_hash != current {
        return Err(format!("stale core record for {name}: recorded {} but the core text now hashes to {current}", core.core_hash));
    }
    if !core.crosschecked || core.mismatches != 0 || core.random_cases < REQUIRED_KERNEL_RANDOM_CASES || core.corner_cases == 0 {
        return Err(format!(
            "{name}: kernel cross-check missing, failed or too small ({} random, {} corner, {} mismatches; need {REQUIRED_KERNEL_RANDOM_CASES} random)",
            core.random_cases, core.corner_cases, core.mismatches
        ));
    }
    let want = cm.imms.first().map(|i| format!("{}..={} (exhaustive)", i.lo, i.hi));
    if core.immediates != want {
        return Err(format!("{name}: kernel cross-check immediates {:?}, need {want:?}", core.immediates));
    }
    Ok(())
}

/// Check one record of a parsed file against the current model source and
/// core text.
pub fn validation_in(file: &EvidenceFile, model: &Model) -> Validation {
    let Some(rec) = file.records.iter().find(|r| r.name == model.name) else {
        return Validation::Missing(format!("no record for {}", model.name));
    };
    let current = model_hash(model);
    if rec.source_hash != current {
        return Validation::Missing(format!(
            "stale record for {}: recorded {} but the model now hashes to {current}",
            model.name, rec.source_hash
        ));
    }
    if let Err(reason) = core_check(file.arch, rec, model) {
        return Validation::Missing(reason);
    }
    if !rec.hosts.is_empty() {
        return host_verdict(model, rec.hosts.iter().filter(|h| h.source_hash == current));
    }
    if file.schema == SCHEMA {
        // Schema 3 keeps every hardware result in `hosts`; a model without
        // any has no evidence (its top-level fields are a summary, never a
        // verdict on their own).
        return Validation::Missing(format!("{}: schema-3 record without host entries", model.name));
    }
    // Schema 1/2: the file's single campaign, on the file's executor.
    match rec.status {
        Status::Validated if !executor_may_validate(&file.executor) => Validation::Missing(format!(
            "{}: validated only under the executor `{}`, which never enables dispatch (only native and rosetta2 results validate)",
            model.name, file.executor
        )),
        Status::Validated if rec.mismatches == 0 && rec.random_cases >= REQUIRED_RANDOM_CASES => {
            Validation::Validated {
                executor: file.executor.clone(),
            }
        }
        Status::Validated => Validation::Missing(format!(
            "{}: only {} random cases (need {REQUIRED_RANDOM_CASES}) or mismatches recorded",
            model.name, rec.random_cases
        )),
        Status::PendingHardware => Validation::PendingHardware,
        Status::Failed => Validation::Missing(format!("{}: campaign failed", model.name)),
    }
}

/// The fail-closed verdict over a model's current host entries: any failure
/// → missing; else validated (a native entry preferred for the executor
/// shown); else pending; else missing.
fn host_verdict<'a>(model: &Model, current: impl Iterator<Item = &'a HostEntry>) -> Validation {
    let cur: Vec<&HostEntry> = current.collect();
    if let Some(f) = cur.iter().find(|h| h.status == Status::Failed || (h.status == Status::Validated && h.mismatches != 0)) {
        return Validation::Missing(format!("{}: campaign failed on {}", model.name, f.cpu_key));
    }
    let mut ok: Vec<&&HostEntry> = cur.iter().filter(|h| h.counts_as_validated()).collect();
    ok.sort_by_key(|h| h.executor != "native");
    if let Some(h) = ok.first() {
        return Validation::Validated { executor: h.executor.clone() };
    }
    if let Some(h) = cur.iter().find(|h| h.status == Status::Validated) {
        return Validation::Missing(if executor_may_validate(&h.executor) {
            format!("{}: only {} random cases on {} (need {REQUIRED_RANDOM_CASES})", model.name, h.random_cases, h.cpu_key)
        } else {
            format!(
                "{}: validated only under the executor `{}` ({}), which never enables dispatch (only native and rosetta2 results validate)",
                model.name, h.executor, h.cpu_key
            )
        });
    }
    if cur.iter().any(|h| h.status == Status::PendingHardware) {
        return Validation::PendingHardware;
    }
    Validation::Missing(format!("{}: no host entry for the current model hash", model.name))
}

/// The verdict for one model restricted to the entries of CPU `cpu_key`
/// (per-microarchitecture reporting; the dispatcher uses [`validation`]).
pub fn validation_on(file: &EvidenceFile, model: &Model, cpu_key: &str) -> Validation {
    let Some(rec) = file.records.iter().find(|r| r.name == model.name) else {
        return Validation::Missing(format!("no record for {}", model.name));
    };
    if let Err(reason) = core_check(file.arch, rec, model) {
        return Validation::Missing(reason);
    }
    let current = model_hash(model);
    if rec.hosts.is_empty() {
        // schema 1/2: the single campaign (a schema-3 model without host
        // entries is missing, see `validation_in`)
        return if file.cpu_key == cpu_key { validation_in(file, model) } else { Validation::Missing(format!("no entry for {cpu_key}")) };
    }
    host_verdict(model, rec.hosts.iter().filter(|h| h.cpu_key == cpu_key && h.source_hash == current))
}

/// Whether the feature-only KATs of `feature` passed on some CPU against the
/// current KAT table, with no current failure anywhere (fail closed). The
/// dispatch glue still runs its own self-test at run time (design §13.2);
/// this is the host-kit evidence that the sets were exercised on real
/// hardware.
pub fn kat_verdict(file: &EvidenceFile, feature: &str) -> Result<Vec<String>, String> {
    let hash = kat::kat_hash();
    let names: Vec<&str> = kat::KATS.iter().filter(|k| k.feature == feature).map(|k| k.name).collect();
    if names.is_empty() {
        return Err(format!("no KATs for `{feature}`"));
    }
    let cur: Vec<&KatRecord> = file.kats.iter().filter(|k| k.feature == feature && k.kat_hash == hash).collect();
    if let Some(f) = cur.iter().find(|k| k.status == "failed") {
        return Err(format!("{} failed on {}", f.name, f.cpu_key));
    }
    let mut keys: Vec<String> = cur.iter().map(|k| k.cpu_key.clone()).collect();
    keys.sort();
    keys.dedup();
    keys.retain(|key| names.iter().all(|n| cur.iter().any(|k| k.cpu_key == *key && k.name == *n && k.status == "passed")));
    if keys.is_empty() { Err(format!("no CPU passed every `{feature}` KAT against the current table")) } else { Ok(keys) }
}

/// Load and parse an evidence file at an arbitrary path (the host kit's
/// output), checking it records `arch`.
pub fn load_path(path: &std::path::Path, arch: Option<Arch>) -> Result<EvidenceFile, String> {
    let text = std::fs::read_to_string(path).map_err(|e| format!("{}: {e}", path.display()))?;
    let file = parse(&text).map_err(|e| format!("{}: {e}", path.display()))?;
    if let Some(a) = arch
        && file.arch != a
    {
        return Err(format!("{}: records arch {}", path.display(), file.arch.name()));
    }
    Ok(file)
}

/// The fail-closed verdict for model `name` of `arch` from the committed file
/// (`Missing` while the model is [`withhold`]en in this process).
pub fn validation(arch: Arch, name: &str) -> Validation {
    let Some(model) = crate::registry::find(arch, name) else {
        return Validation::Missing(format!("{name} is not a registered {} model", arch.name()));
    };
    if is_withheld(arch, name) {
        return Validation::Missing(format!("{name}: evidence withheld in this process (`evidence::withhold`)"));
    }
    match load(arch) {
        Ok(file) => validation_in(&file, model),
        Err(e) => Validation::Missing(e),
    }
}

/// `true` iff emitted code may execute `name` on `arch` (current,
/// hardware-validated evidence).
pub fn is_validated(arch: Arch, name: &str) -> bool {
    matches!(validation(arch, name), Validation::Validated { .. })
}

/// Models whose evidence is withheld in this process: `(guard id, arch, name)`.
static WITHHELD: std::sync::Mutex<Vec<(u64, Arch, String)>> = std::sync::Mutex::new(Vec::new());
static NEXT_WITHHOLD: std::sync::atomic::AtomicU64 = std::sync::atomic::AtomicU64::new(0);

fn is_withheld(arch: Arch, name: &str) -> bool {
    WITHHELD.lock().unwrap_or_else(|e| e.into_inner()).iter().any(|(_, a, n)| *a == arch && n == name)
}

/// Withholds the evidence of the models `names` of `arch` in this process
/// while the returned guard lives: [`validation`] (and so [`is_validated`]
/// and the optimizer's evidence gate and dispatcher) reports them `Missing`,
/// whatever the committed record says.
///
/// Downgrade only, so it can never enable dispatch (§9.2 fail closed); it
/// changes no file. It lets the fail-closed paths (a variant left out of the
/// emitted code, an exported function refused for calling an unvalidated
/// model) stay tested once every real model has hardware evidence. It is
/// process-wide: a test using it must not run concurrently with one that
/// expects those models validated.
#[must_use = "the evidence is withheld only while the guard lives"]
pub fn withhold(arch: Arch, names: &[&str]) -> Withheld {
    let id = NEXT_WITHHOLD.fetch_add(1, std::sync::atomic::Ordering::Relaxed);
    WITHHELD.lock().unwrap_or_else(|e| e.into_inner()).extend(names.iter().map(|n| (id, arch, n.to_string())));
    Withheld { id }
}

/// The guard of [`withhold`]: dropping it restores the models' verdicts.
#[derive(Debug)]
pub struct Withheld {
    id: u64,
}

impl Drop for Withheld {
    fn drop(&mut self) {
        WITHHELD.lock().unwrap_or_else(|e| e.into_inner()).retain(|(id, _, _)| *id != self.id);
    }
}

/// Records of `file` whose hash no longer matches the model source, whose
/// core record is missing or no longer matches the core text, or that are
/// missing (an empty list means the file is current).
pub fn stale(file: &EvidenceFile) -> Vec<String> {
    let mut out = Vec::new();
    for m in file.arch.models() {
        let Some(rec) = file.records.iter().find(|r| r.name == m.name) else {
            out.push(format!("no record for {}", m.name));
            continue;
        };
        let h = model_hash(m);
        if rec.source_hash != h {
            out.push(format!("{}: recorded {} != current {h}", m.name, rec.source_hash));
        }
        match (&rec.core, coretext::find(file.arch, m.name)) {
            (None, _) => out.push(format!("{}: no core record", m.name)),
            (Some(c), Some(cm)) if c.core_hash != cm.hash() => {
                out.push(format!("{}: core recorded {} != current {}", m.name, c.core_hash, cm.hash()))
            }
            (Some(_), None) => out.push(format!("{}: no core-text model", m.name)),
            _ => {}
        }
    }
    out
}

