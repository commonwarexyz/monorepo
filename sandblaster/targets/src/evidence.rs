/// A kernel cross-check campaign to record ([`with_core`]).
#[derive(Clone, Debug)]
pub struct CoreCampaign<'a> {
    /// One outcome per model (named after it), any architecture.
    pub outcomes: &'a [Outcome],
    /// The core-text compression cross-checks.
    pub compositions: &'a [Outcome],
    /// Where the campaign ran (toolchain, profile, date, CPU).
    pub machine: &'a Machine,
    /// The campaign configuration (random cases per model, base seed).
    pub config: &'a Config,
    /// `sha256:<hex>` of the kernel prelude text the models were loaded on.
    pub prelude_hash: &'a str,
}

/// The `core` record of one model, from its kernel cross-check outcome (if any).
pub fn core_json(arch: Arch, model: &Model, outcome: Option<&Outcome>) -> Json {
    let Some(cm) = coretext::find(arch, model.name) else {
        return Json::obj([("status", Json::str("missing")), ("note", Json::str("no core-text model"))]);
    };
    let mut fields: Vec<(String, Json)> = vec![
        ("file".into(), Json::str(coretext::core_file_of(arch, cm.global).unwrap_or(coretext::core_path(arch)))),
        ("global".into(), Json::str(cm.global)),
        ("core_items".into(), Json::Arr(cm.items().into_iter().map(Json::str).collect())),
        ("core_hash".into(), Json::str(cm.hash())),
    ];
    let status = match outcome {
        Some(o) if o.passed() => "cross-checked",
        Some(_) => "failed",
        None => "missing",
    };
    fields.push(("status".into(), Json::str(status)));
    if let Some(o) = outcome {
        let mut k = match outcome_counts(o) {
            Json::Obj(m) => m,
            _ => unreachable!(),
        };
        k.insert(
            0,
            (
                "method".into(),
                Json::str(format!("kernel evaluation of {} vs the executable model {}", cm.global, model.name)),
            ),
        );
        k.push((
            "immediates".into(),
            match &o.immediates {
                Some(r) => Json::str(format!("{}..={} (exhaustive)", r.start(), r.end())),
                None => Json::Null,
            },
        ));
        if let Some(m) = &o.first_mismatch {
            k.push(("first_mismatch".into(), Json::str(m.clone())));
        }
        if let Some(r) = &o.skipped {
            k.push(("skipped".into(), Json::str(r.clone())));
        }
        fields.push(("kernel_crosscheck".into(), Json::Obj(k)));
    }
    Json::Obj(fields)
}

/// Set member `key` of a JSON object (replacing it, or appending it).
fn set_member(obj: &mut Json, key: &str, value: Json) {
    if let Json::Obj(members) = obj {
        match members.iter_mut().find(|(k, _)| k == key) {
            Some((_, v)) => *v = value,
            None => members.push((key.to_string(), value)),
        }
    }
}

/// The models array of an evidence document, mutably.
fn models_mut(doc: &mut Json) -> Option<&mut Vec<Json>> {
    match doc {
        Json::Obj(members) => members.iter_mut().find(|(k, _)| k == "models").and_then(|(_, v)| match v {
            Json::Arr(xs) => Some(xs),
            _ => None,
        }),
        _ => None,
    }
}

/// Record a kernel campaign in an evidence document of `arch`: every model's
/// `core` record (from the outcome named after it) and the top-level
/// `kernel_crosscheck` (with the compositions that concern `arch`). The
/// hardware records are left untouched; the schema becomes [`SCHEMA`] (or
/// [`SCHEMA_V2`] for a document without per-CPU `hosts`).
pub fn with_core(doc: &mut Json, arch: Arch, c: &CoreCampaign) {
    // A schema-2 document (no per-CPU `hosts`) stays schema 2.
    let schema = if doc.get("hosts").is_some() { SCHEMA } else { SCHEMA_V2 };
    set_member(doc, "schema", Json::str(schema));
    if let Some(models) = models_mut(doc) {
        for m in models.iter_mut() {
            let Some(name) = m.get("name").and_then(Json::as_str).map(str::to_string) else { continue };
            let Some(model) = crate::registry::find(arch, &name) else { continue };
            let outcome = c.outcomes.iter().find(|o| o.name == name);
            set_member(m, "core", core_json(arch, model, outcome));
        }
    }
    let compositions: Vec<Json> = c
        .compositions
        .iter()
        .filter(|o| coretext::checks::compress_check_arch(&o.name).is_none_or(|a| a == arch))
        .map(|o| composition_json(o, "core-text compression (kernel evaluation)"))
        .collect();
    let meta = Json::obj([
        (
            "method",
            Json::str(
                "each core model (core/<arch>.core, loaded by Env::load_core after Env::with_prelude) evaluated by the sandblaster kernel on closed inputs and compared with the executable Rust model: corner phase + random phase of the diff harness, every immediate",
            ),
        ),
        ("core_file", Json::str(coretext::core_path(arch))),
        (
            "core_file_hash",
            Json::str(format!(
                "sha256:{}",
                fips::hex(&fips::sha256(coretext::normalize(coretext::core_text(arch)).as_bytes()))
            )),
        ),
        ("prelude_hash", Json::str(c.prelude_hash)),
        ("rustc", Json::str(c.machine.rustc.clone())),
        ("profile", Json::str(c.machine.profile.clone())),
        ("host", Json::str(format!("{} ({})", c.machine.cpu_brand_string, c.machine.executor))),
        ("date", Json::str(c.machine.date.clone())),
        ("random_cases_per_model", Json::uint(c.config.random_per_model)),
        ("base_seed", Json::str(format!("{:#018x}", c.config.seed))),
        ("required_random_cases", Json::uint(REQUIRED_KERNEL_RANDOM_CASES)),
        ("compositions", Json::Arr(compositions)),
    ]);
    set_member(doc, "kernel_crosscheck", meta);
}

/// Carry the core records and the top-level `kernel_crosscheck` of `old`
/// over to a freshly rendered hardware document `doc` (used when the
/// hardware campaign runs without the `kernel` feature). Stale records stay
/// stale: [`stale`] and [`validation_in`] compare their hashes.
pub fn carry_core(doc: &mut Json, old: &Json) {
    let old_models = old.get("models").and_then(Json::as_array).unwrap_or(&[]);
    if let Some(models) = models_mut(doc) {
        for m in models.iter_mut() {
            let name = m.get("name").and_then(Json::as_str).map(str::to_string);
            if let Some(core) = old_models
                .iter()
                .find(|o| o.get("name").and_then(Json::as_str) == name.as_deref())
                .and_then(|o| o.get("core"))
            {
                set_member(m, "core", core.clone());
            }
        }
    }
    if let Some(k) = old.get("kernel_crosscheck") {
        set_member(doc, "kernel_crosscheck", k.clone());
    }
}

