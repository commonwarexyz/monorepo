/// Where a campaign ran.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Machine {
    /// `sysctl -n machdep.cpu.brand_string` (or `/proc/cpuinfo` on Linux).
    pub cpu_brand_string: String,
    /// `native`; `rosetta2` when `sysctl.proc_translated` is 1; the name of
    /// an instruction emulator [`cpu::detect_emulator`] found (`sde`,
    /// `qemu-tcg`, `valgrind`, `dynamorio`); or an explicit
    /// non-validating name ([`Machine::set_executor`]).
    pub executor: String,
    /// Operating system and version.
    pub os: String,
    /// Target features detected at run time (`name: bool`).
    pub detected_features: Vec<(String, bool)>,
    /// `rustc -V` of the compiler that built the campaign.
    pub rustc: String,
    /// The compilation target triple.
    pub target: String,
    /// `debug` or `release`.
    pub profile: String,
    /// `YYYY-MM-DD` (local date; `SANDBLASTER_EVIDENCE_DATE` overrides).
    pub date: String,
    /// CPUID identification (the evidence key), if it could be probed.
    pub cpu: Option<cpu::CpuId>,
}

fn command_output(cmd: &str, args: &[&str]) -> Option<String> {
    let out = std::process::Command::new(cmd).args(args).output().ok()?;
    if !out.status.success() {
        return None;
    }
    let s = String::from_utf8_lossy(&out.stdout).trim().to_string();
    (!s.is_empty()).then_some(s)
}

fn cpu_brand_string() -> String {
    command_output("sysctl", &["-n", "machdep.cpu.brand_string"])
        .or_else(|| {
            let info = std::fs::read_to_string("/proc/cpuinfo").ok()?;
            info.lines()
                .find(|l| l.starts_with("model name") || l.starts_with("Model"))
                .and_then(|l| l.split(':').nth(1))
                .map(|s| s.trim().to_string())
        })
        .unwrap_or_else(|| "unknown".to_string())
}

/// Days since 1970-01-01 → (year, month, day) (Howard Hinnant's algorithm).
fn civil_from_days(z: i64) -> (i64, u32, u32) {
    let z = z + 719_468;
    let era = z.div_euclid(146_097);
    let doe = z.rem_euclid(146_097);
    let yoe = (doe - doe / 1460 + doe / 36_524 - doe / 146_096) / 365;
    let doy = doe - (365 * yoe + yoe / 4 - yoe / 100);
    let mp = (5 * doy + 2) / 153;
    let d = (doy - (153 * mp + 2) / 5 + 1) as u32;
    let m = if mp < 10 { mp + 3 } else { mp - 9 } as u32;
    (yoe + era * 400 + i64::from(m <= 2), m, d)
}

fn today() -> String {
    if let Ok(d) = std::env::var("SANDBLASTER_EVIDENCE_DATE") {
        return d;
    }
    if let Some(d) = command_output("date", &["+%Y-%m-%d"]) {
        return d;
    }
    let secs = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|d| d.as_secs() as i64)
        .unwrap_or(0);
    let (y, m, d) = civil_from_days(secs.div_euclid(86_400));
    format!("{y:04}-{m:02}-{d:02}")
}

impl Machine {
    /// Probe the running machine. `detected_features` comes from the caller
    /// (the architecture-specific [`crate::hw`] module).
    pub fn probe(detected_features: Vec<(String, bool)>) -> Machine {
        let translated =
            command_output("sysctl", &["-n", "sysctl.proc_translated"]).as_deref() == Some("1");
        let os = match command_output("sw_vers", &["-productVersion"]) {
            Some(v) => format!("macOS {v}"),
            None => std::env::consts::OS.to_string(),
        };
        Machine {
            cpu_brand_string: cpu_brand_string(),
            executor: if translated {
                "rosetta2".to_string()
            } else {
                cpu::detect_emulator().unwrap_or_else(|| "native".to_string())
            },
            os,
            detected_features,
            rustc: BUILD_RUSTC.to_string(),
            target: env!("SANDBLASTER_TARGETS_TARGET").to_string(),
            profile: env!("SANDBLASTER_TARGETS_PROFILE").to_string(),
            date: today(),
            cpu: cpu::CpuId::probe(),
        }
    }

    /// Record the campaign under `executor` instead of the probed one (the
    /// evidence binary's `--executor`, for an emulator the probe cannot see,
    /// e.g. QEMU user mode). Only a downgrade is accepted: any
    /// non-validating name may replace the probed executor, but a validating
    /// one ([`VALIDATING_EXECUTORS`]) only when it equals the probed
    /// executor, so the flag can never turn an emulated run into evidence.
    pub fn set_executor(&mut self, executor: &str) -> Result<(), String> {
        let well_formed = !executor.is_empty()
            && executor.len() <= 32
            && executor.bytes().all(|b| b.is_ascii_lowercase() || b.is_ascii_digit() || matches!(b, b'-' | b'_' | b'.'));
        if !well_formed {
            return Err(format!("executor `{executor}`: use 1-32 lower-case letters, digits, `-`, `_` or `.`"));
        }
        if executor_may_validate(executor) && executor != self.executor {
            return Err(format!(
                "executor `{executor}`: the probe found `{}`; an explicit executor may only name a non-validating one (e.g. `emulated`)",
                self.executor
            ));
        }
        self.executor = executor.to_string();
        Ok(())
    }

    /// The key this machine's results are recorded under: the CPUID key
    /// with the executor suffix, or `legacy:<brand> (<executor>)` when no
    /// CPUID could be read.
    pub fn cpu_key(&self) -> String {
        match &self.cpu {
            Some(c) => c.key_on(&self.executor),
            None => legacy_key(&self.cpu_brand_string, &self.executor),
        }
    }
}

/// The key of a campaign without CPUID identification (schema-2 records).
pub fn legacy_key(brand: &str, executor: &str) -> String {
    format!("legacy:{brand} ({executor})")
}

