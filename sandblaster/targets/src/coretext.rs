/// The core models of an architecture (same order as [`Arch::models`]).
pub fn models(arch: Arch) -> &'static [CoreModel] {
    match arch {
        Arch::Aarch64 => AARCH64_CORE_MODELS,
        Arch::X86_64 => X86_64_CORE_MODELS,
    }
}

/// The core model of `name` (a stdarch intrinsic name) on `arch`.
pub fn find(arch: Arch, name: &str) -> Option<&'static CoreModel> {
    models(arch).iter().find(|m| m.name == name)
}

/// Normalize a Rust path for lookup: drop a leading `::` and read `std::`
/// as `core::` (`::std::arch::aarch64::vaddq_u32` → `core::arch::aarch64::vaddq_u32`).
fn normalize_path(path: &str) -> String {
    let p = path.trim().trim_start_matches("::");
    match p.strip_prefix("std::") {
        Some(rest) => format!("core::{rest}"),
        None => p.to_string(),
    }
}

/// The core model of an intrinsic by its Rust path
/// (`core::arch::aarch64::vaddq_u32`, also with a leading `::` or `std::`).
pub fn find_by_path(path: &str) -> Option<&'static CoreModel> {
    let p = normalize_path(path);
    AARCH64_CORE_MODELS.iter().chain(X86_64_CORE_MODELS).find(|m| m.rust_path() == p)
}

