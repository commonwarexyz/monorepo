/// A lane (machine word) type of the kernel.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum Lane {
    /// `U8`.
    U8,
    /// `U16`.
    U16,
    /// `U32`.
    U32,
    /// `U64`.
    U64,
}

impl Lane {
    /// The core type name (`U32`).
    pub fn core_name(self) -> &'static str {
        match self {
            Lane::U8 => "U8",
            Lane::U16 => "U16",
            Lane::U32 => "U32",
            Lane::U64 => "U64",
        }
    }

    /// The literal suffix (`u32`).
    pub fn suffix(self) -> &'static str {
        match self {
            Lane::U8 => "u8",
            Lane::U16 => "u16",
            Lane::U32 => "u32",
            Lane::U64 => "u64",
        }
    }

    /// Width in bits.
    pub fn bits(self) -> u32 {
        match self {
            Lane::U8 => 8,
            Lane::U16 => 16,
            Lane::U32 => 32,
            Lane::U64 => 64,
        }
    }
}

/// The core type of a value parameter or result.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum CoreTy {
    /// A machine word (`U32`).
    Word(Lane),
    /// A fixed-length array of lanes, lane 0 first (`Array U32 4usize`).
    Vector(Lane, u32),
}

impl CoreTy {
    /// The type in core text.
    pub fn text(self) -> String {
        match self {
            CoreTy::Word(l) => l.core_name().to_string(),
            CoreTy::Vector(l, n) => format!("Array {} {n}usize", l.core_name()),
        }
    }
}

use CoreTy::{Vector, Word};

/// NEON `uint8x16_t` / x86 `__m128i`.
const U8X16: CoreTy = Vector(Lane::U8, 16);
/// NEON `uint8x8_t`.
const U8X8: CoreTy = Vector(Lane::U8, 8);
/// NEON `uint32x4_t` (also `[u32; 4]`).
const U32X4: CoreTy = Vector(Lane::U32, 4);
/// NEON `uint16x8_t`.
const U16X8: CoreTy = Vector(Lane::U16, 8);
/// NEON `uint64x2_t`.
const U64X2: CoreTy = Vector(Lane::U64, 2);
/// NEON `uint32x2_t`.
const U32X2: CoreTy = Vector(Lane::U32, 2);
/// x86 `__m256i`.
const U8X32: CoreTy = Vector(Lane::U8, 32);
/// `[u32; 8]` (the AVX2 lane kernels' pack/unpack arrays).
const U32X8: CoreTy = Vector(Lane::U32, 8);
/// `[u32; 16]` (the AVX-512 lane kernels' pack/unpack arrays).
const U32X16: CoreTy = Vector(Lane::U32, 16);
/// x86 `__m512i`.
const U8X64: CoreTy = Vector(Lane::U8, 64);

/// An immediate parameter (a stdarch `const` generic) and its accepted range.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub struct CoreImm {
    /// Parameter name (`N`, `LANE`, `IMM8`).
    pub name: &'static str,
    /// Smallest accepted value.
    pub lo: u32,
    /// Largest accepted value.
    pub hi: u32,
}

/// One binder of a core global's Π telescope.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Binder {
    /// Binder name.
    pub name: String,
    /// `false` for the irrelevant range proofs.
    pub relevant: bool,
    /// The binder's type in core text.
    pub ty: String,
    /// What the argument is.
    pub role: Role,
}

/// The role of a binder, telling a caller what to pass.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Role {
    /// The immediate itself: a `U32` literal in range.
    Imm {
        /// Index into [`CoreModel::imms`].
        index: usize,
    },
    /// A range proof of the preceding immediate: pass `.refl(Bool, true)`.
    ImmProof {
        /// Index into [`CoreModel::imms`].
        index: usize,
    },
    /// A value argument.
    Value {
        /// Index into [`CoreModel::params`].
        index: usize,
    },
}

/// A core-text model: the `def[intrinsic]` global transcribing one
/// intrinsic of the registry, and its signature.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct CoreModel {
    /// Architecture.
    pub arch: Arch,
    /// The stdarch name (the registry's [`Model::name`]).
    pub name: &'static str,
    /// The core global name (`aarch64::vaddq_u32`).
    pub global: &'static str,
    /// Immediates, in order (they come first in the telescope).
    pub imms: &'static [CoreImm],
    /// Value parameters `(name, type)` in stdarch order.
    pub params: &'static [(&'static str, CoreTy)],
    /// Result type.
    pub ret: CoreTy,
}

impl CoreModel {
    /// The registry entry of the executable model.
    pub fn model(&self) -> &'static Model {
        registry::find(self.arch, self.name).expect("every core model has a registry entry (tested)")
    }

    /// The `core::arch` path the intrinsic prints as.
    pub fn rust_path(&self) -> &'static str {
        self.model().rust_path
    }

    /// The full telescope: immediates with their range proofs, then values.
    pub fn telescope(&self) -> Vec<Binder> {
        let mut out = Vec::new();
        for (index, imm) in self.imms.iter().enumerate() {
            out.push(Binder {
                name: imm.name.to_string(),
                relevant: true,
                ty: "U32".to_string(),
                role: Role::Imm { index },
            });
            if imm.lo > 0 {
                out.push(Binder {
                    name: format!("h{}0", imm.name),
                    relevant: false,
                    ty: format!("Eq(Bool, #le_u32({}u32, {}), true)", imm.lo, imm.name),
                    role: Role::ImmProof { index },
                });
            }
            out.push(Binder {
                name: format!("h{}", imm.name),
                relevant: false,
                ty: format!("Eq(Bool, #le_u32({}, {}u32), true)", imm.name, imm.hi),
                role: Role::ImmProof { index },
            });
        }
        for (index, (name, ty)) in self.params.iter().enumerate() {
            out.push(Binder {
                name: name.to_string(),
                relevant: true,
                ty: ty.text(),
                role: Role::Value { index },
            });
        }
        out
    }

    /// The global's type in core text, e.g.
    /// `(N : U32) -> (.hN : Eq(Bool, #le_u32(N, 31u32), true)) -> (a : Array U32 4usize) -> Array U32 4usize`.
    pub fn type_text(&self) -> String {
        let mut s = String::new();
        for b in self.telescope() {
            let dot = if b.relevant { "" } else { "." };
            s.push_str(&format!("({dot}{} : {}) -> ", b.name, b.ty));
        }
        s.push_str(&self.ret.text());
        s
    }

    /// A call in core text: `imms` are the immediate values (checked against
    /// their ranges), `args` the core text of the value arguments.
    pub fn apply_text(&self, imms: &[u32], args: &[&str]) -> Result<String, String> {
        if imms.len() != self.imms.len() || args.len() != self.params.len() {
            return Err(format!(
                "{} takes {} immediate(s) and {} argument(s), got {} and {}",
                self.global,
                self.imms.len(),
                self.params.len(),
                imms.len(),
                args.len()
            ));
        }
        let mut s = self.global.to_string();
        for b in self.telescope() {
            match b.role {
                Role::Imm { index } => {
                    let (v, imm) = (imms[index], self.imms[index]);
                    if v < imm.lo || v > imm.hi {
                        return Err(format!("{}: immediate {} = {v} out of range {}..={}", self.global, imm.name, imm.lo, imm.hi));
                    }
                    s.push_str(&format!(" {v}u32"));
                }
                Role::ImmProof { .. } => s.push_str(" .refl(Bool, true)"),
                Role::Value { index } => s.push_str(&format!(" ({})", args[index])),
            }
        }
        Ok(s)
    }

    /// The core items defining this model: the global first, then every
    /// helper it uses (transitively), in file order.
    pub fn items(&self) -> Vec<&'static str> {
        core_items(self.arch, self.global)
    }

    /// The core hash of this model ([`core_hash`]).
    pub fn hash(&self) -> String {
        core_hash(self.arch, self.global)
    }
}

const fn imm(name: &'static str, lo: u32, hi: u32) -> CoreImm {
    CoreImm { name, lo, hi }
}

macro_rules! core_model {
    ($arch:ident, $prefix:literal, $name:ident, [$($imm:expr),*], [$($p:ident : $t:expr),*], $ret:expr) => {
        CoreModel {
            arch: Arch::$arch,
            name: stringify!($name),
            global: concat!($prefix, stringify!($name)),
            imms: &[$($imm),*],
            params: &[$((stringify!($p), $t)),*],
            ret: $ret,
        }
    };
}

macro_rules! a64 {
    ($name:ident, [$($imm:expr),*], [$($p:ident : $t:expr),*], $ret:expr) => {
        core_model!(Aarch64, "aarch64::", $name, [$($imm),*], [$($p : $t),*], $ret)
    };
}

macro_rules! x86 {
    ($name:ident, [$($imm:expr),*], [$($p:ident : $t:expr),*], $ret:expr) => {
        core_model!(X86_64, "x86_64::", $name, [$($imm),*], [$($p : $t),*], $ret)
    };
}

