//! The kernel core-text transcriptions of the target models and their
//! registry (DESIGN.md §9.2 "core-text transcription", §5.12 core syntax).
//!
//! `core/aarch64.core` and `core/x86_64.core` transcribe every executable
//! model of [`crate::aarch64`] / [`crate::x86_64`] into kernel core text as a
//! `def[intrinsic]` global over the prelude's `Array` types, lane-level,
//! following `MODELS.md`. They load with `Env::load_core` after
//! `Env::with_prelude()` (see `crate::kernel`, feature `kernel`). This
//! module needs no kernel: it embeds the text ([`core_text`]), describes each
//! global's signature for the front end / elaborator ([`CoreModel`],
//! [`CoreHelper`]), and hashes the text of each model's core items for the
//! evidence records ([`core_hash`], [`core_items`]).
//!
//! **Signature convention** (normative; `MODELS.md` "Core text"):
//!
//! * vectors are `Array <lane> <N>usize` (NEON `uint32x4_t` = `Array U32
//!   4usize`, `uint8x16_t` = `Array U8 16usize`, `uint8x8_t` = `Array U8
//!   8usize`; x86 `__m128i` = `Array U8 16usize` little-endian);
//! * immediates (stdarch `const N: i32`) come **first**, as relevant `U32`
//!   parameters, each followed by its irrelevant range proofs — `(.hN0 :
//!   Eq(Bool, #le_u32(lo, N), true))` only if `lo > 0`, then `(.hN :
//!   Eq(Bool, #le_u32(N, hi), true))`. The caller passes `.refl(Bool, true)`
//!   for a literal in range ([`CoreModel::apply_text`] does); an out-of-range
//!   immediate is ill-typed;
//! * then the value parameters in stdarch order; `&[T; N]` arguments of the
//!   pointer-free loads are arrays (`&T` is `T` in the core, §3.5);
//! * signed stdarch scalars (`_mm_set_epi32`, `_mm_set_epi64x`) are passed as
//!   their two's-complement bits (`U32` / `U64`).
#![forbid(unsafe_code)]

use crate::fips;
use crate::registry::{self, Arch, Model};

/// `core/aarch64.core`: the aarch64 NEON + SHA2 core models.
pub const AARCH64_CORE: &str = include_str!("../core/aarch64.core");

/// `core/x86_64.core`: the x86_64 SSE + SHA-NI core models (hand-written).
pub const X86_64_CORE_SSE: &str = include_str!("../core/x86_64.core");

/// `core/x86_64_avx.core`: the x86_64 256/512-bit core models (AVX-512F/BW/
/// VL/DQ, IFMA, GFNI, VBMI/VBMI2, VPOPCNTDQ/BITALG, AVX2), generated by
/// `gen/x86_64_avx.py`. It reuses helpers of `core/x86_64.core`.
pub const X86_64_CORE_AVX: &str = include_str!("../core/x86_64_avx.core");

/// The x86_64 core text: `core/x86_64.core` followed by
/// `core/x86_64_avx.core`, loaded as one text. (Appending items leaves every
/// earlier model's [`core_hash`] unchanged: an item's hashed text is its own
/// comment-free text, and only comments separate the two files.)
pub const X86_64_CORE: &str = concat!(include_str!("../core/x86_64.core"), include_str!("../core/x86_64_avx.core"));

/// The core text of an architecture's models (load after the prelude).
pub fn core_text(arch: Arch) -> &'static str {
    match arch {
        Arch::Aarch64 => AARCH64_CORE,
        Arch::X86_64 => X86_64_CORE,
    }
}

/// Path of an architecture's (first) core file relative to the crate root.
pub fn core_path(arch: Arch) -> &'static str {
    match arch {
        Arch::Aarch64 => "core/aarch64.core",
        Arch::X86_64 => "core/x86_64.core",
    }
}

/// The core files of an architecture, in load order, with their texts
/// ([`core_text`] is their concatenation).
pub fn core_files(arch: Arch) -> &'static [(&'static str, &'static str)] {
    match arch {
        Arch::Aarch64 => &[("core/aarch64.core", AARCH64_CORE)],
        Arch::X86_64 => &[("core/x86_64.core", X86_64_CORE_SSE), ("core/x86_64_avx.core", X86_64_CORE_AVX)],
    }
}

/// The core file defining item `name` of `arch`.
pub fn core_file_of(arch: Arch, name: &str) -> Option<&'static str> {
    core_files(arch).iter().find(|(_, text)| item_names(text).contains(&name)).map(|(path, _)| *path)
}

/// The global-name prefix of an architecture's core items (`aarch64::`).
pub fn global_prefix(arch: Arch) -> &'static str {
    match arch {
        Arch::Aarch64 => "aarch64::",
        Arch::X86_64 => "x86_64::",
    }
}

