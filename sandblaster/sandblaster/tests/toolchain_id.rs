//! The toolchain identity (`toolchain_id.rs`, computed by the facade's
//! `build.rs`; DESIGN.md §2.1 *Re-runs*): a content hash of the toolchain
//! that does not depend on where or how it was compiled, and changes with
//! anything that can change a verdict. Each property has a negative twin.

#[path = "../toolchain_id.rs"]
mod toolchain_id;

use std::collections::BTreeMap;
use std::path::{Path, PathBuf};

use toolchain_id::{closure, hex, identity, local_packages, parse_lock, sha256, tree_digest};

#[test]
fn sha256_matches_fips_180_4() {
    assert_eq!(hex(&sha256(b"")), "e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855");
    assert_eq!(hex(&sha256(b"abc")), "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad");
    assert_eq!(hex(&sha256(b"abcdbcdecdefdefgefghfghighijhijkijkljklmklmnlmnomnopnopq")), "248d6a61d20638b8e5c026930c3e6039a33ce45964ff2167f6ecedd419db06c1");
    assert_eq!(hex(&sha256(&[b'a'; 1000])), "41edece42d63e8d9bf515a9ba6932e1c20cbc9f5a5d134645adb5db1b9737ea3");
}

