//! Copies the frozen O1 emission of the general corpus (`../baselines/o1-gen.rs`, checksummed in
//! `../baselines/SHA256SUMS`, verified by `../run.sh`) to `OUT_DIR/gen.rs`, refusing anything but
//! verified and optimized sandblaster output of the corpus root.
fn main() {
    let src = format!("{}/../baselines/o1-gen.rs", std::env::var("CARGO_MANIFEST_DIR").unwrap());
    println!("cargo::rerun-if-changed={src}");
    let text = std::fs::read_to_string(&src).unwrap_or_else(|e| panic!("{src}: {e}"));
    let header = text.lines().next().unwrap_or("");
    if !header.starts_with("// @generated by sandblaster") || !header.contains("opt_corpus/dsl/mod.rs`") || !text.lines().nth(1).unwrap_or("").starts_with("// STATUS: VERIFIED + OPTIMIZED") {
        eprintln!("error: {src} is not verified, optimized sandblaster output of the corpus root");
        std::process::exit(1);
    }
    std::fs::write(std::path::Path::new(&std::env::var("OUT_DIR").unwrap()).join("gen.rs"), text).unwrap();
}
