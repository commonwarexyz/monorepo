//! Copies the generated corpus (`OPT_CORPUS_GENERATED_RS`, written by
//! `bench/opt-corpus/run.sh` with the front end's stage emitter) to
//! `OUT_DIR/gen.rs`, refusing anything but the optimized **stage output**
//! of the corpus root (`// STATUS: STAGE OUTPUT (…)`: the corpus is a
//! toolchain test program, DESIGN.md §15.8). It is the only consumer that
//! accepts stage output, and it accepts nothing else: not a crate verdict
//! (the corpus is not built through `sandblaster::build::compile`), not the
//! output of another root, not output modified for testing.
const ENV: &str = "OPT_CORPUS_GENERATED_RS";
const ROOT: &str = "opt_corpus/dsl/mod.rs`";

fn main() {
    println!("cargo::rerun-if-env-changed={ENV}");
    let Ok(src) = std::env::var(ENV) else {
        eprintln!("error: set {ENV} to the generated corpus (bench/opt-corpus/run.sh emits it)");
        std::process::exit(1);
    };
    println!("cargo::rerun-if-changed={src}");
    let text = std::fs::read_to_string(&src).unwrap_or_else(|e| panic!("{src}: {e}"));
    let header = text.lines().next().unwrap_or("");
    if !header.starts_with("// @generated by sandblaster") || !header.contains(ROOT) {
        eprintln!("error: {src} is not sandblaster output of the corpus root ({header})");
        std::process::exit(1);
    }
    let status = text.lines().nth(1).unwrap_or("");
    if status != "// STATUS: STAGE OUTPUT (not a crate verdict: the §15 gates did not run)" || !text.contains("\n// The optimizer's results are kernel-checked and this file passed the round trip.\n") {
        eprintln!("error: {src} is not the optimized stage output of the corpus (stage_emit) ({status})");
        std::process::exit(1);
    }
    let out = std::path::Path::new(&std::env::var("OUT_DIR").unwrap()).join("gen.rs");
    std::fs::write(out, text).unwrap();
}
