//! Residue-number-system arithmetic on one base field element at a time.
//!
//! This follows VROOM (<https://eprint.iacr.org/2026/393>); see NOTICE. An [`Rns`] holds an
//! integer `u` congruent to `a * M` modulo `p` for the field value `a`, as its residues modulo
//! [`RESIDUES`] pairwise coprime moduli `q` just below `2^50`: the [`MODULI`] of the first basis,
//! with product `M`, and the [`MODULI`] of the second basis, with product `N`. Each basis also
//! scales its residues by a fixed constant that the conversion tables absorb, which leaves
//! addition and subtraction residue-wise.
//!
//! The residues of each basis occupy one register, residue `i` in lane `i`, which is VROOM's
//! layout. Values therefore require x86v4c, whose eight 64-bit lanes match the eight moduli.
//!
//! Multiplication is Montgomery multiplication modulo `M`. Both bases multiply residue-wise. The
//! first basis then reduces its products into a quotient that cancels the product modulo `M`, and
//! a base conversion carries that quotient into the second basis, where adding it times `p` and
//! dividing by `M` are residue-wise. The conversion multiplies rotated copies of the quotient by
//! fixed diagonals of the conversion matrix and skips the quotient estimate of an exact
//! conversion, so the converted quotient may exceed the exact one by a bounded multiple of `M`,
//! which only adds a bounded multiple of `p` to the result. Extension of the result back to the
//! first basis must be exact, so it estimates its quotient with fixed-point fractions in scalar
//! arithmetic and broadcasts each residue against a row of the conversion matrix. Every residue
//! product is a pair of 52-bit multiply-adds (`u64_madd52lo` and `u64_madd52hi`), which AVX-512
//! IFMA provides natively, and residues are reduced with one 52-bit Montgomery step each.
//!
//! The tables are generated by `scripts/parameters.py`, which checks them against a model of this
//! arithmetic. The bounds below are also asserted at compile time.
//!
//! # Usage
//!
//! A value holds one element. Elements cross the boundary as [`BYTES`]-byte big-endian integers
//! below `2^384`, which loads interpret modulo `p` and stores return canonically.
//!
//! Every operation returns residues at most twice their moduli, so values never need carrying or
//! preparing before a multiplication: only the integer `u` grows. A subtraction or negation bias
//! `K` must be at least the bound of the value it removes.
//!
//! # Bounds
//!
//! Each value carries a debug-only integer bound in units of `p`. For bounds `A` and `B`:
//!
//! | Operation | Requires | Integer bound |
//! |---|---|---|
//! | load, splat | | `2` |
//! | `a + b` | | `A + B` |
//! | `a - b` with bias `K` | `B <= K` | `A + K` |
//! | `-a` with bias `K` | `A <= K` | `K` |
//! | `a * b` | | `ceil(A * B / floor(M / p)) + 16` |
//!
//! Every integer bound is at most [`LIMIT`], which keeps products within the Montgomery reduction
//! and every value within exact extension and canonicalization. Debug builds check these rules;
//! release builds do not, and results are unspecified when a formula violates them.
//!
//! # Lazy products
//!
//! As a crate-private `Field`, products stay unreduced as `Wide` sums of the `(high, low)`
//! accumulators of both bases, and one reduction, the second half of [`Rns::mul`], serves a whole sum.
//! Sums carry an integer bound in units of `p^2`: a product of bounds `A` and `B` contributes `A * B`, a
//! lift multiplies by the representative of one, below `p`, and so contributes `A`, and a sum
//! reduces to at most `REDUCED` when its bound is at most `BUDGET`. A subtraction first reduces
//! the subtrahend's accumulators residue-wise to at most `2q`, keeping their congruence, and
//! subtracts them from a constant congruent to `SUB_BIAS * p^2`; the subtrahend's bound must be at
//! most `SUB_BIAS`, which the result's bound gains. Accumulators hold at most `TERMS` terms, a
//! product or lift counting one and a subtraction `SUB_TERMS`.

