#[cfg(test)]
mod tests {
    use super::ROOTS;

    #[test]
    fn axes_and_quarter_turns() {
        assert_eq!(ROOTS[0], (1 << 48, 0));
        assert_eq!(ROOTS[1], (0, 1 << 48));
        for pair in ROOTS.as_chunks::<2>().0 {
            assert_eq!(pair[1], (-pair[0].1, pair[0].0));
        }
    }

    #[test]
    fn rounded_unit_semicircle() {
        let scale = 1i128 << 48;
        for &(re, im) in &ROOTS {
            assert!(i128::from(re).abs() <= scale);
            assert!((0..=scale).contains(&i128::from(im)));
            let norm = i128::from(re).pow(2) + i128::from(im).pow(2);
            assert!((norm - scale * scale).abs() <= 2 * scale + 1);
        }
    }
}
