fn from_values(logn: u32, limbs: usize, values: &[i128]) -> Poly {
    assert_eq!(values.len(), 1 << logn);
    assert!(limbs <= 4);
    let mut p = Poly::zero(logn, limbs);
    for (i, &x) in values.iter().enumerate() {
        for j in 0..limbs {
            p.words[j * values.len() + i] = ((x >> (31 * j)) as u32) & MASK;
        }
    }
    p
}

fn values(p: &Poly) -> Vec<i128> {
    assert!(p.limbs <= 4);
    (0..p.n())
        .map(|i| {
            let mut x = 0i128;
            for j in 0..p.limbs {
                x |= i128::from(p.words[j * p.n() + i]) << (31 * j);
            }
            if p.words[(p.limbs - 1) * p.n() + i] >> 30 != 0 {
                x -= 1i128 << (31 * p.limbs);
            }
            x
        })
        .collect()
}

fn multiply(a: &[i128], b: &[i128]) -> Vec<i128> {
    assert_eq!(a.len(), b.len());
    let n = a.len();
    let mut result = vec![0; n];
    for (i, &x) in a.iter().enumerate() {
        for (j, &y) in b.iter().enumerate() {
            if i + j < n {
                result[i + j] += x * y;
            } else {
                result[i + j - n] -= x * y;
            }
        }
    }
    result
}

fn negate_odd(a: &[i128]) -> Vec<i128> {
    a.iter()
        .enumerate()
        .map(|(i, &x)| if i & 1 == 0 { x } else { -x })
        .collect()
}

fn embedded(a: &[i128]) -> Vec<i128> {
    a.iter().flat_map(|&x| [x, 0]).collect()
}

#[test]
fn signed_limb_roundtrip_and_resize_boundaries() {
    let inputs = [
        -(1i128 << 62),
        -(1 << 31) - 1,
        -(1 << 30) - 1,
        -(1 << 30),
        -1,
        0,
        (1 << 30) - 1,
        (1 << 62) - 1,
    ];
    let p = from_values(3, 3, &inputs);
    assert_eq!(values(&p), inputs);
    assert_eq!(&*p.small_values().unwrap(), &inputs.map(|x| x as i64));
    assert!(p.resized(2).is_none());
    let q = from_values(2, 3, &[-(1 << 30), -1, 0, (1 << 30) - 1]);
    let one = q.resized(1).unwrap();
    assert_eq!(values(&one), values(&q));
    assert_eq!(values(&one.resized(4).unwrap()), values(&q));
    for x in [-(1i128 << 30) - 1, 1 << 30] {
        assert!(from_values(0, 2, &[x]).resized(1).is_none());
    }
    for x in [-(1i128 << 62) - 1, 1 << 62] {
        assert!(from_values(0, 3, &[x]).small_values().is_none());
    }
}

#[test]
fn signed_scaled_windows_match_exact_floor() {
    for bit in [
        0, 1, 11, 12, 13, 29, 30, 31, 32, 47, 48, 49, 61, 62, 63, 92, 93, 100,
    ] {
        for x in [(1i128 << bit) - 1, 1 << bit, (1 << bit) + 1] {
            for x in [x, -x] {
                let p = from_values(0, 4, &[x]);
                for shift in [
                    0, 1, 14, 16, 17, 30, 31, 32, 47, 48, 49, 61, 62, 63, 78, 92, 93, 100, 112,
                    124, 155,
                ] {
                    for factor in [1, 36] {
                        if p.bits() + if factor == 36 { 6 } else { 0 } > shift + 12 {
                            assert!(p.scaled(shift, factor).is_none());
                            continue;
                        }
                        let expected = if shift <= 48 {
                            x << (48 - shift)
                        } else {
                            x >> (shift - 48)
                        };
                        assert_eq!(
                            p.scaled(shift, factor).unwrap()[0],
                            expected * factor,
                            "x={x}, shift={shift}, factor={factor}"
                        );
                    }
                }
            }
        }
    }
}

