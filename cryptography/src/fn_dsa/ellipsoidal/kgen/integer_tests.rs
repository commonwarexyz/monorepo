#[test]
fn public_capacity_bounds_cover_input_recurrence_and_lifts() {
    let bounds = INPUT_BITS;
    assert_eq!(bounds.len(), 10);
    assert_eq!(bounds[0], 7);
    assert!(303032 < 1 << bounds[1]);
    assert!(PRIMES.iter().all(|sp| sp.p > 1 << 30 && sp.p % 2048 == 1));
    for (i, a) in PRIMES.iter().enumerate() {
        for b in &PRIMES[..i] {
            let (mut x, mut y) = (a.p, b.p);
            while y != 0 {
                (x, y) = (y, x % y);
            }
            assert_eq!(x, 1);
        }
    }
    for (depth, &bound) in bounds.iter().enumerate().skip(1) {
        let m = 1u32 << depth;
        let logn = 9 - depth as u32;
        let exponent = logn * (m / 2 - 1) + 19 * (m / 2);
        assert_eq!(bound, exponent);
    }
    let mut largest_lift_count = 0;
    for depth in 0..10 {
        let output = bounds[depth] + 16;
        let mut needs = vec![bounds[depth], output];
        if depth < 9 {
            let logn = 9 - depth as u32;
            let lift = bounds[depth] + bounds[depth + 1] + 16 + logn;
            largest_lift_count = largest_lift_count.max(prime_count(lift));
            needs.push(lift);
            let max_scale = lift.div_ceil(8) * 8;
            assert!(max_scale / 8 + 1 < 1024);
            let capacity = bounds[depth] + max_scale + logn + 34;
            assert!(31 * limb_count(capacity) as u32 > capacity);
        }
        for bound in needs {
            let count = prime_count(bound);
            assert!(count <= PRIMES.len());
            assert!(30 * count as u32 > bound);
            assert!(31 * limb_count(bound) as u32 > bound);
        }
    }
    assert_eq!(largest_lift_count, 249);
}

