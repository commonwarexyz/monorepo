#[test]
fn descent_and_lift_match_schoolbook_and_preserve_determinant() {
    for logn in 1..=5 {
        let n = 1 << logn;
        let f: Vec<_> = (0..n).map(|i| (i * 17 % 11) as i128 - 5).collect();
        let g: Vec<_> = (0..n).map(|i| (i * 7 % 13) as i128 - 6).collect();
        let pair = Pair {
            f: from_values(logn, 2, &f),
            g: from_values(logn, 2, &g),
        };
        let lower = descend(&pair, 24);
        let fnorm = multiply(&f, &negate_odd(&f));
        let gnorm = multiply(&g, &negate_odd(&g));
        assert!(fnorm.iter().skip(1).step_by(2).all(|&x| x == 0));
        assert!(gnorm.iter().skip(1).step_by(2).all(|&x| x == 0));
        assert_eq!(
            values(&lower.f),
            fnorm.iter().step_by(2).copied().collect::<Vec<_>>()
        );
        assert_eq!(
            values(&lower.g),
            gnorm.iter().step_by(2).copied().collect::<Vec<_>>()
        );
        let big_f: Vec<_> = (0..n / 2).map(|i| (i * 19 % 17) as i128 - 8).collect();
        let big_g: Vec<_> = (0..n / 2).map(|i| (i * 23 % 19) as i128 - 9).collect();
        let big = Pair {
            f: from_values(logn - 1, 2, &big_f),
            g: from_values(logn - 1, 2, &big_g),
        };
        let lifted = lift(&pair, &big, 24);
        let expected_f = multiply(&embedded(&big_f), &negate_odd(&g));
        let expected_g = multiply(&embedded(&big_g), &negate_odd(&f));
        assert_eq!(values(&lifted.f), expected_f);
        assert_eq!(values(&lifted.g), expected_g);
        let left = multiply(&f, &expected_g);
        let right = multiply(&g, &expected_f);
        let low_left = multiply(&values(&lower.f), &big_g);
        let low_right = multiply(&values(&lower.g), &big_f);
        let low_det: Vec<_> = low_left.iter().zip(low_right).map(|(x, y)| x - y).collect();
        assert_eq!(
            left.iter()
                .zip(right)
                .map(|(x, y)| x - y)
                .collect::<Vec<_>>(),
            embedded(&low_det)
        );
    }
}

#[test]
fn scaled_subtraction_matches_exact_negacyclic_product() {
    let small_values = [-24, 25, -1, 0, 1, 24, -25, 7];
    let k = [1 << 20, -(1 << 20), -1, 0, 1, 3, -7, 12];
    let small = from_values(3, 1, &small_values);
    let product = multiply(&small_values, &k.map(i128::from));
    let initial = [-(1i128 << 110), (1 << 109) - 1, -1, 0, 1, 37, -83, 24];
    for scale in [0, 1, 30, 31, 32, 61, 62, 63] {
        let mut big = from_values(3, 4, &initial);
        big.sub_scaled(&small, &k, scale);
        let expected: Vec<_> = initial
            .iter()
            .zip(&product)
            .map(|(x, y)| x - (y << scale))
            .collect();
        assert_eq!(values(&big), expected, "scale={scale}");
    }
}

